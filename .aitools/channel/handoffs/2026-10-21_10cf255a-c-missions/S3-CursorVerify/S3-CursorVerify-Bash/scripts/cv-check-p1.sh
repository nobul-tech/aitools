#!/usr/bin/env bash
# cv-check-p1.sh ROOT PHASEDIR -- P1 assertions; writes PHASEDIR/checks.txt (PASS/FAIL lines + evidence)
set -uo pipefail
ROOT="$1"; O="$2"; A="$ROOT/aitools"; D="$ROOT/dotprofile"; H="$ROOT/home"
OUT="$O/checks.txt"; : > "$OUT"
say() { printf '%s\n' "$*" >> "$OUT"; }
res() { if [ "$1" = 0 ]; then say "PASS $2"; else say "FAIL $2"; fi; }
MARK="<!-- aitools-fanout: generated by setup-user-cursor from ~/.aitools/rules/"

# 1. expected rule stems: git-tracked top-level files of the three sources whose name ends in .md (any case)
{
  git -C "$A/shared/rules" ls-files | perl -ne 'chomp; print "$_\n" if !m{/} && /\.md\z/i'
  git -C "$A/.claude/rules" ls-files | perl -ne 'chomp; print "$_\n" if !m{/} && /\.md\z/i'
  git -C "$D/claude/rules" ls-files | perl -ne 'chomp; print "$_\n" if !m{/} && /\.md\z/i'
} | perl -ne 'chomp; s/\.md\z//i; print lc($_)."\n"' | LC_ALL=C sort -u > "$O/expected-rule-stems.txt"
( cd "$H/.cursor/rules" && ls -1 ) | perl -ne 'chomp; next if /\.bak\./; next unless s/\.mdc\z//; next if $_ eq "user-own"; print lc($_)."\n"' | LC_ALL=C sort -u > "$O/actual-rule-stems.txt"
if diff "$O/expected-rule-stems.txt" "$O/actual-rule-stems.txt" > "$O/rule-stems.diff"; then rc=0; else rc=1; fi
res $rc "rules: every rule stem of shared/.claude/dotprofile has a ~/.cursor/rules/<stem>.mdc (diff: rule-stems.diff)"
say "  expected $(grep -c . "$O/expected-rule-stems.txt") stems, actual $(grep -c . "$O/actual-rule-stems.txt")"
perl -ne 'print "  $_"' "$O/rule-stems.diff" >> "$OUT"

# 2. marker on the line after the frontmatter, in every fanned-out .mdc
miss=0
for f in "$H/.cursor/rules/"*.mdc; do
    b=$(basename "$f"); [ "$b" = "user-own.mdc" ] && continue
    if ! perl -e 'local $/; open my $h,"<",$ARGV[0] or exit 2; my $t=<$h>; exit(($t =~ /\A---\n(?:(?!---\n)[^\n]*\n)*---\n\Q$ARGV[1]\E/) ? 0 : 1)' "$f" "$MARK"; then
        say "  no marker: $b"; miss=$((miss + 1))
    fi
done
res $miss "rules: fan-out marker after the frontmatter in every fanned-out .mdc"
if grep -q "aitools-fanout" "$H/.cursor/rules/user-own.mdc"; then res 1 "user-own.mdc has no marker"; else res 0 "user-own.mdc has no marker"; fi

# 3. first source wins (rules)
grep -q "SHARED copy (must win)" "$H/.cursor/rules/fx-dup.mdc"; res $? "rules: fx-dup.mdc is the shared copy"
grep -q "AITOOLS copy (must win over dotprofile)" "$H/.cursor/rules/fx-dup2.mdc"; res $? "rules: fx-dup2.mdc is the aitools .claude copy"
grep -q "SHARED copy (must win)" "$H/.aitools/rules/fx-dup.md"; res $? "harness: ~/.aitools/rules/fx-dup.md is the shared copy"
grep -q "AITOOLS copy" "$H/.aitools/rules/fx-dup2.md"; res $? "harness: ~/.aitools/rules/fx-dup2.md is the aitools copy"

# 4. skills: every file under ~/.aitools/skills/<name> (not hidden, not .bak.) equals ~/.cursor/skills/<name>/<rel>, mode equal
bad=0; n=0
while IFS= read -r rel; do
    n=$((n + 1))
    if ! cmp -s "$H/.aitools/skills/$rel" "$H/.cursor/skills/$rel"; then say "  differs/missing: $rel"; bad=$((bad + 1)); continue; fi
    m1=$(perl -e 'printf "%04o", (stat $ARGV[0])[2] & 07777' "$H/.aitools/skills/$rel")
    m2=$(perl -e 'printf "%04o", (stat $ARGV[0])[2] & 07777' "$H/.cursor/skills/$rel")
    if [ "$m1" != "$m2" ]; then say "  mode $m1 vs $m2: $rel"; bad=$((bad + 1)); fi
done < <(cd "$H/.aitools/skills" && find . -type f ! -name '.*' | perl -ne 's{\A\./}{}; print unless m{(?:\A|/)[^/]*\.bak\.}i' | LC_ALL=C sort)
res $bad "skills: $n harness skill files present and identical (content + mode) under ~/.cursor/skills"
m=$(perl -e 'printf "%04o", (stat $ARGV[0])[2] & 07777' "$H/.cursor/skills/fx-skill-a/scripts/run.sh")
[ "$m" = "0755" ]; res $? "skills: exec bit kept on fx-skill-a/scripts/run.sh (mode $m)"

# 5. every winning skill of the three sources is in ~/.aitools/skills and ~/.cursor/skills
{
  git -C "$A/shared/skills" ls-files | perl -ne 'print "$1\n" if m{\A([^/]+)/}'
  git -C "$A/.claude/skills" ls-files | perl -ne 'print "$1\n" if m{\A([^/]+)/}'
  git -C "$D/claude/skills" ls-files | perl -ne 'print "$1\n" if m{\A([^/]+)/}'
} | perl -ne 'chomp; next if /\A\./ || /\.bak\./i; print lc($_)."\n"' | LC_ALL=C sort -u > "$O/expected-skills.txt"
( cd "$H/.cursor/skills" && ls -1 ) | perl -ne 'chomp; next if $_ eq "user-skill"; print lc($_)."\n"' | LC_ALL=C sort -u > "$O/actual-skills.txt"
if diff "$O/expected-skills.txt" "$O/actual-skills.txt" > "$O/skills.diff"; then rc=0; else rc=1; fi
res $rc "skills: every skill name of shared/.claude/dotprofile is a ~/.cursor/skills dir (diff: skills.diff)"
perl -ne 'print "  $_"' "$O/skills.diff" >> "$OUT"

# 6. first source wins (skills)
grep -q "aitools shared/skills (must win)" "$H/.cursor/skills/fx-dupskill/SKILL.md"; res $? "skills: fx-dupskill is the shared copy"
grep -q "must win over dotprofile" "$H/.cursor/skills/fx-dupskill2/SKILL.md"; res $? "skills: fx-dupskill2 is the aitools .claude copy"

# 7. ERROR rows: one per skipped duplicate (5 expected) and matching log_error lines
n=$(grep -c '^ERROR|harness files|.*dup in' "$O/harness.summary")
[ "$n" = 5 ]; res $? "harness: 5 duplicate ERROR rows (found $n)"
grep '^ERROR|harness files|' "$O/harness.summary" | perl -ne 'print "  row: $_"' >> "$OUT"
grep 'Duplicate .* name' "$O/harness.out" | perl -ne 'print "  log: $_"' >> "$OUT"

# 8. bracket names
[ -f "$H/.cursor/rules/fx-[br].mdc" ]; res $? "bracket: ~/.cursor/rules/fx-[br].mdc exists"
[ -f "$H/.cursor/skills/fx-[br]ack/SKILL.md" ]; res $? "bracket: ~/.cursor/skills/fx-[br]ack/SKILL.md exists"

# 9. FX-Upper.MD
say "INFO FX-Upper.MD:"
for p in "$H/.aitools/rules/FX-Upper.MD" "$H/.cursor/rules/FX-Upper.mdc"; do
    if [ -e "$p" ]; then say "  present: $p"; else say "  absent: $p"; fi
done
if grep -q 'FX-Upper' "$H/.aitools/rules/.aitools-rules-manifest"; then say "  in rules manifest: yes"; else say "  in rules manifest: no"; fi
grep -n 'FX-Upper' "$O/deploy.log.copy" | perl -ne 'print "  deploy.log: $_"' >> "$OUT"
grep -n 'FX-Upper' "$O/harness.out" "$O/cursor.out" | perl -ne 'print "  console: $_"' >> "$OUT"

# 10. user files untouched (content, mode, mtime): snap-before vs snap-after lines
for p in ".cursor/rules/user-own.mdc" ".cursor/skills/user-skill" ".cursor/skills/user-skill/SKILL.md"; do
    b=$(grep -F "$p	" "$O/snap-before.txt" | head -1); a=$(grep -F "$p	" "$O/snap-after.txt" | head -1)
    if [ -n "$b" ] && [ "$b" = "$a" ] && ! [ "$p" = ".cursor/skills/user-skill" ]; then res 0 "user file untouched: $p"
    elif [ "$p" = ".cursor/skills/user-skill" ]; then
        b4=$(printf '%s' "$b" | cut -f1-4); a4=$(printf '%s' "$a" | cut -f1-4)
        [ "$b4" = "$a4" ]; res $? "user dir untouched (type/mode): $p"
    else res 1 "user file untouched: $p (before: $b | after: $a)"; fi
done
# no backup files anywhere under ~/.cursor after a first run
nb=$(cd "$H" && find .cursor -name '*.bak.*' | grep -c .)
say "INFO *.bak.* entries under ~/.cursor after this phase: $nb"
nd=$(cd "$H" && find .cursor -maxdepth 1 -name '*.bak.*' | grep -c .)
say "INFO directory backups beside ~/.cursor/rules and ~/.cursor/skills: $nd"
grep -n 'backup_dir' "$O/deploy.log.copy" | perl -ne 'print "  deploy.log: $_"' >> "$OUT"
