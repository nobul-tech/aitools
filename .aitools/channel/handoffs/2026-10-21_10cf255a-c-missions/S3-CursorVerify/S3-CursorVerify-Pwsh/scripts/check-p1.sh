#!/usr/bin/env bash
# check-p1.sh -- S3-CursorVerify-Pwsh P1 content checks (read-only)
set -uo pipefail
S=/Users/new-jose/repos/aitools/.claude/worktrees/cverify/.scratch/session-cv-ps
H="$S/fx/home"; O="$S/out/P1"
echo "== harness rules (non-hidden) vs cursor .mdc count"
ls "$H/.aitools/rules" | grep -vc '^\.'
ls "$H/.cursor/rules" | grep -c '\.mdc$'
echo "== cursor .mdc without the fan-out marker (expect only user-own.mdc)"
grep -L 'aitools-fanout: generated by setup-user-cursor' "$H/.cursor/rules/"*.mdc
echo "== first-source-wins content"
grep -h 'Fixture dup' "$H/.cursor/rules/fx-dup.mdc" "$H/.cursor/rules/fx-dup2.mdc" "$H/.aitools/rules/fx-dup.md" "$H/.aitools/rules/fx-dup2.md"
grep -h '^description' "$H/.cursor/skills/fx-dupskill/SKILL.md" "$H/.cursor/skills/fx-dupskill2/SKILL.md" "$H/.aitools/skills/fx-dupskill/SKILL.md" "$H/.aitools/skills/fx-dupskill2/SKILL.md"
echo "== fx-[br] rule and fx-[br]ack skill"
ls -la "$H/.cursor/rules/fx-[br].mdc" "$H/.cursor/skills/fx-[br]ack/SKILL.md" "$H/.aitools/skills/fx-[br]ack/SKILL.md"
echo "== FX-Upper"
head -8 "$H/.cursor/rules/FX-Upper.mdc"
echo "== run.sh modes (source, harness, cursor)"
ls -l "$S/fx/aitools/shared/skills/fx-skill-a/scripts/run.sh" "$H/.aitools/skills/fx-skill-a/scripts/run.sh" "$H/.cursor/skills/fx-skill-a/scripts/run.sh"
echo "== user files vs P0"
grep -E 'user-own|user-skill' "$S/out/P0/snap.txt" > "$O/user-p0.tmp"
grep -E 'user-own|user-skill' "$O/snap.txt" > "$O/user-p1.tmp"
diff "$S/out/P0/snap.txt" "$S/out/P0/snap.txt" > /dev/null
if diff "$O/user-p0.tmp" "$O/user-p1.tmp"; then echo "user files identical (content, mode, mtime)"; fi
cat "$O/user-p1.tmp"
echo "== skill dirs harness vs cursor"
ls "$H/.aitools/skills" | grep -v '^\.' | sort > "$O/skills-h.tmp"
ls "$H/.cursor/skills" | sort > "$O/skills-c.tmp"
diff "$O/skills-h.tmp" "$O/skills-c.tmp"
echo "== harness skill files vs cursor skill files"
( cd "$H/.aitools/skills" && find . -type f ! -name '.aitools-skills-manifest' | sort ) > "$O/sf-h.tmp"
( cd "$H/.cursor/skills" && find . -type f ! -path './user-skill/*' | sort ) > "$O/sf-c.tmp"
wc -l < "$O/sf-h.tmp"; wc -l < "$O/sf-c.tmp"
diff "$O/sf-h.tmp" "$O/sf-c.tmp"
echo "== skill source files vs harness: shared+.claude+dotprofile git-tracked count"
echo "== backups anywhere"
find "$H/.cursor" "$H/.aitools" -name '*.bak.*' | grep -v '/logs/'
echo "== frontmatter sample fx-shared.mdc"
head -6 "$H/.cursor/rules/fx-shared.mdc"
