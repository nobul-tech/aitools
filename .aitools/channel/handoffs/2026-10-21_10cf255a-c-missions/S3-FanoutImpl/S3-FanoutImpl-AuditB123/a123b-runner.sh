#!/usr/bin/env bash
# a123b-runner.sh -- runtime logging audit of setup-user-cursor.sh/.ps1 steps 4
# (rules fan-out) and 5 (skills fan-out), PR #123 @ 880749e.
# Per case and language: a fresh isolated HOME ($OUT/<case>/<lang>), seeded by
# seed_<case>; sh runs a123b-step45.sh (steps 4-5 text + exit footer of the
# .sh), ps runs tests/rules-fanout-cursor/step4-driver.ps1 (steps 4-5 of the
# .ps1; the Windows OS guard is outside the extracted text), stdin /dev/null.
# Captured: <lang>.rc, <lang>.out, <lang>.summary, <lang>.deploy.log
# ($HOME/.aitools/logs/deploy.log, AITOOLS_LOG_DIR unset), <lang>.tree.
# Usage: bash a123b-runner.sh WORKTREE OUTDIR [case...]
set -uo pipefail

WT="${1:?usage: a123b-runner.sh WORKTREE OUTDIR [case...]}"
OUT="${2:?usage}"
shift 2
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SH_DRIVER="$HERE/a123b-step45.sh"
PS_DRIVER="$WT/tests/rules-fanout-cursor/step4-driver.ps1"
PTY="$WT/tests/managed-files/pty-run.py"
case "$OUT" in /Users/new-jose|/Users/new-jose/.claude*|/Users/new-jose/.aitools*|/Users/new-jose/.cursor*) echo "refusing OUT"; exit 1 ;; esac
mkdir -p "$OUT"

MARK='<!-- aitools-fanout: generated by setup-user-cursor from ~/.aitools/rules/'
skill() { mkdir -p "$1/$2"; printf -- '---\nname: %s\n---\n%s\n' "$2" "$3" > "$1/$2/SKILL.md"; }
rmanifest() { mkdir -p "$H/.aitools/rules"; { printf '%s\n' "${RHEAD:-# aitools rules manifest v1}"; for l in "$@"; do printf '%s\n' "$l" | tr '|' '\t'; done; } > "$H/.aitools/rules/.aitools-rules-manifest"; }
smanifest() { mkdir -p "$H/.aitools/skills"; { printf '%s\n' "${SHEAD:-# aitools skills manifest v1}"; for l in "$@"; do printf '%s\n' "$l" | tr '|' '\t'; done; } > "$H/.aitools/skills/.aitools-skills-manifest"; }

# Harness + target trees covering: shared/aitools/dotprofile sources, backups,
# non-rule file, retired-and-fan-out-created (removed), retired-and-user-owned
# (kept: WARN + ACTION), unmanaged user files (preserved), a local edit
# (overwritten non-interactively), an executable skill file.
base_tree() {
    local R="$H/.aitools/rules" S="$H/.aitools/skills" CR="$H/.cursor/rules" CS="$H/.cursor/skills"
    mkdir -p "$R" "$S" "$CR" "$CS"
    printf '## Shared rule\n' > "$R/s.md"
    printf -- '---\npaths:\n  - scripts/**\n---\n## Project rule\n' > "$R/p.md"
    printf '## Dotprofile rule\n' > "$R/d.md"
    printf 'old shared\n' > "$R/s.md.bak.2026-10-22T010203Z"
    printf 'not a rule\n' > "$R/notes.txt"
    printf -- '---\nalwaysApply: true\n---\n%sgone.md; edit that rule, not this file -->\n## Gone\n' "$MARK" > "$CR/gone.mdc"
    printf -- '---\nalwaysApply: true\n---\nmy own old\n' > "$CR/mineold.mdc"
    printf -- '---\nalwaysApply: true\n---\nmine\n' > "$CR/user.mdc"
    skill "$S" alpha "harness alpha"
    skill "$S" beta "harness beta"
    mkdir -p "$S/beta/scripts"; printf '#!/bin/sh\necho hi\n' > "$S/beta/scripts/run.sh"; chmod +x "$S/beta/scripts/run.sh"
    mkdir -p "$S/gone.bak.20261020T000000Z"; printf -- '---\nname: gone\n---\ngone skill\n' > "$S/gone.bak.20261020T000000Z/SKILL.md"
    skill "$CS" gone "gone skill"
    skill "$CS" mineold "my own old skill"
    skill "$CS" thirdparty "third party"
    skill "$CS" alpha "locally edited alpha"
}
manifests_ok() {
    rmanifest "s.md|shared" "p.md|aitools" "d.md|dotprofile" "gone.md|retired" "mineold.md|retired"
    smanifest "alpha|shared" "beta|aitools" "gone|retired" "mineold|retired"
}

seed_happy()       { base_tree; manifests_ok; }
seed_rerun()       { base_tree; manifests_ok; }
twice_rerun=1
seed_nomanifest()  { base_tree; }
seed_badheader()   { base_tree; RHEAD="# rules v0" SHEAD="# skills v0"; manifests_ok; }
seed_badline()     { base_tree; rmanifest "s.md|shared" "p.md|bogus" "a/b.md|shared" "missing.md|shared" "gone.md|retired"; smanifest "alpha|shared" "beta|bogus" ".hid|shared" "missing|shared" "gone|retired"; }
seed_mfunread()    { base_tree; manifests_ok; chmod 000 "$H/.aitools/rules/.aitools-rules-manifest" "$H/.aitools/skills/.aitools-skills-manifest"; }
seed_mfdir()       { base_tree; mkdir "$H/.aitools/rules/.aitools-rules-manifest" "$H/.aitools/skills/.aitools-skills-manifest"; }
seed_srcdangle()   { base_tree; manifests_ok; ln -s "$H/nowhere.md" "$H/.aitools/rules/dang.md"; ln -s "$H/nowhere" "$H/.aitools/skills/dang"; }
seed_dstdangle()   { base_tree; manifests_ok; ln -s "$H/nowhere.mdc" "$H/.cursor/rules/s.mdc"; rm -rf "$H/.cursor/skills/alpha"; ln -s "$H/nowhere" "$H/.cursor/skills/alpha"; }
seed_srcunread()   { base_tree; manifests_ok; chmod 000 "$H/.aitools/rules/s.md" "$H/.aitools/skills/alpha/SKILL.md"; }
seed_dirunread()   { base_tree; manifests_ok; chmod 000 "$H/.aitools/rules" "$H/.aitools/skills"; }
seed_bakparent()   { base_tree; manifests_ok; chmod 555 "$H/.cursor"; }
seed_bakrules()    { base_tree; manifests_ok; chmod 555 "$H/.cursor/rules" "$H/.cursor/skills"; }
seed_nocreate()    { mkdir -p "$H/.cursor"; base_tree; manifests_ok; rm -rf "$H/.cursor/rules" "$H/.cursor/skills"; printf 'a file\n' > "$H/.cursor/rules"; printf 'a file\n' > "$H/.cursor/skills"; }
seed_dryrun()      { base_tree; manifests_ok; }
flags_dryrun="--dry-run -DryRun"
seed_drynocreate() { seed_nocreate; }
flags_drynocreate="--dry-run -DryRun"
seed_noharness()   { mkdir -p "$H/.cursor"; }
seed_emptyharness(){ mkdir -p "$H/.aitools/rules" "$H/.aitools/skills" "$H/.cursor"; }
seed_onlyretired() { mkdir -p "$H/.cursor"; rmanifest "gone.md|retired"; smanifest "gone|retired"; }

ALL_CASES="happy rerun nomanifest badheader badline mfunread mfdir srcdangle dstdangle srcunread dirunread bakparent bakrules nocreate dryrun drynocreate noharness emptyharness onlyretired"
CASES="${*:-$ALL_CASES}"

envs() {  # HOME summary
    E=(env -u AITOOLS_FORCE -u AITOOLS_DRY_RUN -u AITOOLS_LOG_DIR -u AITOOLS_ENVIRONMENT -u CLAUDE_CODE_REMOTE
       -u AITOOLS_USER_REPO_PATH -u AITOOLS_PROFILE_SH -u AITOOLS_PROFILE_PS1
       HOME="$1" USERPROFILE="$1" AITOOLS_SUMMARY_FILE="$2" NO_COLOR=1)
}
run_one() {  # case lang flag
    local cs="$1" lang="$2" flag="$3" C="$OUT/$1" h="$OUT/$1/$2"
    envs "$h" "$C/$lang.summary"
    : > "$C/$lang.summary"
    if [ "$lang" = sh ]; then
        "${E[@]}" bash "$SH_DRIVER" "$WT/scripts/setup-user-cursor.sh" ${flag:+"$flag"} < /dev/null > "$C/sh.out" 2>&1
    else
        "${E[@]}" pwsh -NoProfile -File "$PS_DRIVER" "$WT/scripts/setup-user-cursor.ps1" ${flag:+"$flag"} < /dev/null > "$C/ps.out" 2>&1
    fi
    echo $? > "$C/$lang.rc"
}

for cs in $CASES; do
    C="$OUT/$cs"
    if [ -d "$C" ]; then chmod -R u+rwx "$C"; rm -rf "$C"; fi
    mkdir -p "$C"
    fl_var="flags_$cs"; fl="${!fl_var:-}"
    tw_var="twice_$cs"; tw="${!tw_var:-}"
    shf="${fl%% *}"; psf="${fl##* }"
    for lang in sh ps; do
        H="$C/$lang"; mkdir -p "$H"
        RHEAD=""; SHEAD=""
        "seed_$cs"
        if [ "$lang" = sh ]; then f="$shf"; else f="$psf"; fi
        if [ -n "$tw" ]; then
            run_one "$cs" "$lang" "$f"
            mv "$H/.aitools/logs/deploy.log" "$C/$lang.first.deploy.log"
            cp "$C/$lang.summary" "$C/$lang.first.summary"
        fi
        run_one "$cs" "$lang" "$f"
    done
    chmod -R u+rwx "$C"
    for lang in sh ps; do
        if [ -f "$C/$lang/.aitools/logs/deploy.log" ]; then cp "$C/$lang/.aitools/logs/deploy.log" "$C/$lang.deploy.log"; else : > "$C/$lang.deploy.log"; fi
        ( cd "$C/$lang" && find .cursor -print 2>/dev/null | perl -pe 's/\.bak\.[0-9TZ-]+/.bak.TS/g' | sort ) > "$C/$lang.tree"
    done
    printf '%-14s sh=%s ps=%s\n' "$cs" "$(cat "$C/sh.rc")" "$(cat "$C/ps.rc")"
done

# --- pty cases: review menu on a terminal, [s]kip and [x]abort, rules then skills ---
seed_ptyrules()  { base_tree; manifests_ok; printf -- '---\nalwaysApply: true\n---\n%ss.md; edit that rule, not this file -->\n## Shared rule\nmy edit\n' "$MARK" > "$H/.cursor/rules/s.mdc"; rm -rf "$H/.cursor/skills/alpha"; }
seed_ptyskills() { mkdir -p "$H/.cursor"; smanifest "alpha|shared"; skill "$H/.aitools/skills" alpha "harness alpha"; skill "$H/.cursor/skills" alpha "my edit"; }
if [ -z "${*:-}" ] || [ "${PTY_CASES:-}" = 1 ]; then
  for pc in ptyrules ptyskills; do
    for key in s x; do
        cs="${pc}_$key"; C="$OUT/$cs"
        if [ -d "$C" ]; then chmod -R u+rwx "$C"; rm -rf "$C"; fi
        mkdir -p "$C"
        for lang in sh ps; do
            H="$C/$lang"; mkdir -p "$H"; "seed_$pc"
            envs "$H" "$C/$lang.summary"; : > "$C/$lang.summary"
            if [ "$lang" = sh ]; then
                "${E[@]}" python3 "$PTY" --input "$key\\n" --log "$C/sh.out" -- bash "$SH_DRIVER" "$WT/scripts/setup-user-cursor.sh" > /dev/null 2>&1
            else
                "${E[@]}" python3 "$PTY" --input "$key\\n" --log "$C/ps.out" -- pwsh -NoProfile -File "$PS_DRIVER" "$WT/scripts/setup-user-cursor.ps1" > /dev/null 2>&1
            fi
            echo $? > "$C/$lang.rc"
            if [ -f "$H/.aitools/logs/deploy.log" ]; then cp "$H/.aitools/logs/deploy.log" "$C/$lang.deploy.log"; else : > "$C/$lang.deploy.log"; fi
            ( cd "$H" && find .cursor -print 2>/dev/null | perl -pe 's/\.bak\.[0-9TZ-]+/.bak.TS/g' | sort ) > "$C/$lang.tree"
        done
        printf '%-14s sh=%s ps=%s\n' "$cs" "$(cat "$C/sh.rc")" "$(cat "$C/ps.rc")"
    done
  done
fi
