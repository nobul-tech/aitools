# deploy-harness.ps1 -- populate %USERPROFILE%\.aitools, the deployed harness, from the repos (Windows)
#
# Creates %USERPROFILE%\.aitools\{reference,registries,hooks,rules,skills,bin},
# deploys every source file into it through Deploy-ManagedFile (summary tool
# "harness files", adopt target = the repo file), and generates
# %USERPROFILE%\.aitools\config.json from profile.json by calling the only
# config writer, setup-user-config.ps1.
#
# Safe to re-run: a file equal to its source is verified and not written.
# Platform: Windows. On macOS/Linux use deploy-harness.sh (same sources, order,
#   conflicts, outcomes and exit codes; the .sh also sets the executable bit).
# Reference: reference/harness.md "Deployed harness (~/.aitools)" (sources,
#   conflict handling, assumptions); managed tools: none installed here
#   (/tool-registry skill).
#
# --- BEGIN scope (extracted by build-deploy) ---
# Managed (each file through Deploy-ManagedFile; git-tracked source files only):
#   .aitools\reference\**        <- <aitools>\reference\**
#   .aitools\registries\**       <- <aitools>\registries\**
#   .aitools\hooks\<file>        <- <aitools>\shared\hooks, then <aitools>\.claude\hooks (flat)
#   .aitools\skills\<name>\**    <- <aitools>\shared\skills, <aitools>\.claude\skills,
#                                   <dotprofile>\claude\skills (one directory per skill)
#   .aitools\rules\<file>.md     <- <aitools>\shared\rules, <aitools>\.claude\rules,
#                                   <dotprofile>\claude\rules (one flat directory)
#   .aitools\bin\<cli>           <- <aitools>\scripts\{harness-db.py,read-session.py,read-session-full.py}
#   .aitools\config.json         <- generated by setup-user-config.ps1 (its own managed fields);
#                                   not run with -SkipConfig (row "config.json n/a")
#   .aitools\rules\.aitools-rules-manifest   <- written every run (sole owner): one
#                                   "<file name><TAB><source>" line per rule (section 5b)
#   .aitools\skills\.aitools-skills-manifest <- written every run (sole owner): one
#                                   "<skill name><TAB><source>" line per skill (section 5b)
#                                   Source: shared | aitools | dotprofile | retired.
# Name conflicts: the first source wins; each skipped duplicate is LogError +
#   an ERROR row. Unit: file name (rules, hooks), skill directory name (skills);
#   compared case-insensitively. Files named *.bak.* are never deployed, nor
#   skill directories whose name starts with "." or contains ".bak." (".bak."
#   matched case-insensitively).
# Retired: a rule or skill in the previous manifest that no source has any more
#   (only when its source was listed this run). A retired rule's file is backed
#   up and removed from .aitools\rules; a retired skill's directory is copied
#   to .aitools\skills\<name>.bak.<UTC>\ (copy verified; the newest 5 kept)
#   and removed from .aitools\skills. The manifest keeps the "retired" line
#   until a source has the name again.
# Preserved: every other file under .aitools (logs, backups, files with no
#   source -- each logged, never deleted; backups and the manifests are not listed).
# Overwrites: no -- a deployed file that differs from its source gets the review menu.
# --- END scope (extracted by build-deploy) ---
#
# Usage: deploy-harness.ps1 [-DryRun] [-Force] [-SkipConfig] [-Help]
#   -DryRun       report what would change; write nothing (also AITOOLS_DRY_RUN=1)
#   -Force        no review menu: source wins (also AITOOLS_FORCE=1)
#   -SkipConfig   do not run the config writer (the caller already ran it, e.g.
#                 aitools-install Step 5); summary row OK "config.json"
#                 "n/a (written by installer)"
# Exit: 0 done (warnings possible), 1 errors (incl. duplicates, config.json
#   not generated), 2 aborted by the user at a review menu.
# Marker lines ("BEGIN|END <name> (extracted|replaced by build-deploy)") mark
# the spans build-deploy.sh copies into the MDM variant (<dotprofile>\deploy\).

# --- BEGIN body (extracted by build-deploy) ---
param(
    [switch]$DryRun,
    [switch]$Force,
    [switch]$SkipConfig,
    [switch]$Help
)

. (Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) "aitools-lib.ps1")
Initialize-Logging "deploy-harness"

# --- OS guard ---
if ($PSVersionTable.PSVersion.Major -ge 6 -and -not $IsWindows) {
    LogError "This script is for Windows. On macOS/Linux, use the .sh version."
    exit 1
}

$tool = "harness files"
$scriptPath = $MyInvocation.MyCommand.Path

# --- Flags ---
if ($Help) {
    # The header comment (to the first non-comment line), "# " removed;
    # the build-deploy span markers are not shown.
    foreach ($line in (Get-Content -LiteralPath $scriptPath)) {
        if ($line -notmatch '^#') { break }
        if ($line -match '^# --- (BEGIN|END) ') { continue }
        [Console]::WriteLine(($line -replace '^# ?', ''))
    }
    exit 0
}
if ($args.Count -gt 0) {
    LogError "Unknown option: $($args -join ' ') (see -Help)"
    Write-Summary "ERROR" $tool "bad arguments"
    exit 1
}
if ($env:AITOOLS_DRY_RUN -eq "1") { $DryRun = [switch]::Present }
if ($env:AITOOLS_FORCE -eq "1") { $Force = [switch]::Present }
# Non-empty: the config writer is not run; the reason goes in the summary row.
# Not named $skipConfig: PowerShell names are case-insensitive, so that would be
# the [switch] parameter and hold $true / $false.
$configSkip = if ($SkipConfig) { "written by installer" } else { "" }
# The library reads $Force / AITOOLS_FORCE; the config writer inherits it.
if ($Force) { $env:AITOOLS_FORCE = "1" }
if ($DryRun) { Log "[DRY RUN] Preview mode -- no files will be written" }

$scriptDir = Split-Path -Parent $scriptPath
$repoDir = Split-Path -Parent $scriptDir
$harnessDir = Join-Path $env:USERPROFILE ".aitools"

# Short summary detail: at most 30 characters (script-standards).
function Get-ShortDetail([string]$Text) {
    if ($Text.Length -gt 30) { return $Text.Substring(0, 27) + "..." }
    return $Text
}

# =========================================================================
# 1. config.json -- generated from profile.json by the only writer
# =========================================================================
$configWriter = Join-Path $scriptDir "setup-user-config.ps1"
# --- BEGIN config bootstrap check (replaced by build-deploy) ---
# Dev path: aitools-install writes the bootstrap keys (reposPath, repoPath)
# before any run, so the writer always runs unless -SkipConfig. The MDM
# variant checks for the keys here and skips the writer without them.
# --- END config bootstrap check (replaced by build-deploy) ---
if ($configSkip) {
    # One path for -SkipConfig and the MDM no-bootstrap case: not an error.
    Log "config.json: setup-user-config.ps1 not run ($configSkip)"
    Write-Summary "OK" "config.json" (Get-ShortDetail "n/a ($configSkip)")
} elseif (-not (Test-Path -LiteralPath $configWriter)) {
    LogError "config.json: writer not found at $configWriter -- config.json not generated"
    Write-Summary "ERROR" $tool "config.json not generated"
} else {
    Log "config.json: generating from profile.json (setup-user-config.ps1)"
    $global:LASTEXITCODE = 0
    $cwRc = 0
    try {
        if ($DryRun) { & $configWriter -DryRun } else { & $configWriter }
        $cwRc = $LASTEXITCODE
    } catch {
        LogError "config.json: setup-user-config.ps1 threw: $_"
        $cwRc = 1
    }
    if ($cwRc -and $cwRc -ne 0) {
        LogError "config.json: setup-user-config.ps1 failed (exit $cwRc) -- see its log lines above"
        Write-Summary "ERROR" $tool "config.json not generated"
    }
}

# --- BEGIN dotprofile lookup (replaced by build-deploy) ---
# =========================================================================
# 2. Dotprofile (source of user rules and skills): userRepoPath in config.json
# =========================================================================
$dotprofile = $null
$urp = ReadConfigKey -File (Join-Path $harnessDir "config.json") -Key "userRepoPath"
if (-not $urp) {
    Log "No userRepoPath in $(Join-Path $harnessDir 'config.json') -- dotprofile rules and skills skipped (run: aitools user init)"
} elseif (-not (Test-Path -LiteralPath $urp -PathType Container)) {
    Log "Dotprofile $urp not found -- dotprofile rules and skills skipped"
} else {
    $dotprofile = $urp
}

# --- END dotprofile lookup (replaced by build-deploy) ---
# =========================================================================
# 3. The six directories
# =========================================================================
$kinds = @("reference", "registries", "hooks", "rules", "skills", "bin")
foreach ($kind in $kinds) {
    $d = Join-Path $harnessDir $kind
    if (Test-Path -LiteralPath $d -PathType Container) { continue }
    if ($DryRun) {
        Log "[DRY RUN] Would create $d"
        continue
    }
    try {
        New-Item -ItemType Directory -Path $d -Force -ErrorAction Stop | Out-Null
        Log "Created $d"
    } catch {
        LogError "Cannot create ${d}: $_"
        Write-Summary "ERROR" $tool (Get-ShortDetail "cannot create $kind/")
    }
}

# =========================================================================
# 4. Plan: every source file, conflicts resolved (first source wins)
# =========================================================================
$plan = [System.Collections.Generic.List[object]]::new()
$seen = @{}          # "<kind>|<lowercased unit>" -> @{ Label; Unit }
$listed = @{}        # "<kind>|<source label>" per source listed this run (section 5b:
                     # only these retire names, per kind)
$duplicates = 0

# Add-Source KIND LABEL SRC_DIR DEST_DIR LAYOUT
#   LAYOUT tree   : every file, relative paths kept, no conflicts (reference, registries)
#          flat   : top-level files only; unit = file name (hooks)
#          flat-md: top-level *.md files only (extension any case); unit = file name (rules)
#          units  : files inside top-level directories; unit = directory name (skills)
function Add-Source {
    param([string]$Kind, [string]$Label, [string]$SrcDir, [string]$DestDir, [string]$Layout)
    if (-not (Test-Path -LiteralPath $SrcDir -PathType Container)) {
        Log "Source $Label not found ($SrcDir) -- skipped"
        return
    }
    # 2>$null: rev-parse fails outside a git work tree; that failure is the answer
    # ($LASTEXITCODE checked on the next line).
    $null = & git -C $SrcDir rev-parse --is-inside-work-tree 2>$null
    if ($LASTEXITCODE -ne 0) {
        LogError "Source $Label ($SrcDir) is not in a git work tree -- skipped (only git-tracked files are deployed)"
        Write-Summary "ERROR" $tool (Get-ShortDetail "${Label}: not a git checkout")
        return
    }
    # UTF-8 for git's output (non-ASCII names; cross-platform-detail.md "PowerShell pipeline encoding")
    $errFile = [IO.Path]::GetTempFileName()
    $prevEnc = [Console]::OutputEncoding
    try {
        [Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false)
        $raw = & git -C $SrcDir ls-files -z 2> $errFile
        $lsRc = $LASTEXITCODE
    } finally {
        [Console]::OutputEncoding = $prevEnc
    }
    $lsErr = [IO.File]::ReadAllText($errFile)
    Remove-Item -LiteralPath $errFile -Force -ErrorAction SilentlyContinue
    # ErrorAction exempt: temp file cleanup; nothing depends on it
    if ($lsRc -ne 0) {
        LogError "Source ${Label}: git ls-files failed in ${SrcDir}: $lsErr"
        Write-Summary "ERROR" $tool (Get-ShortDetail "${Label}: git ls-files failed")
        return
    }
    $listed["$Kind|$Label"] = $true
    $files = @((@($raw) -join "") -split "`0" | Where-Object { $_ })
    $lastUnit = ""
    $keepUnit = $true
    $n = 0
    foreach ($rel in $files) {
        $base = ($rel -split '/')[-1]
        if ($base -like '*.bak.*') { LogDetail "skip backup copy: $Label/$rel"; continue }
        $unit = ""
        switch ($Layout) {
            { $_ -in @("flat", "flat-md") } {
                if ($rel.Contains('/')) { LogDetail "skip nested file in a flat source: $Label/$rel"; $unit = $null; break }
                if ($Layout -eq "flat-md" -and $rel -notlike '*.md') {
                    LogDetail "skip non-.md file in a rules source: $Label/$rel"; $unit = $null; break
                }
                $unit = $rel
            }
            "units" {
                if (-not $rel.Contains('/')) { LogDetail "skip file outside a skill directory: $Label/$rel"; $unit = $null; break }
                $unit = ($rel -split '/')[0]
                # Not a skill name (the manifest's name rule): hidden or a backup directory
                if ($unit.StartsWith('.') -or $unit -like '*.bak.*') {
                    LogDetail "skip file in a hidden or backup directory: $Label/$rel"; $unit = $null; break
                }
            }
        }
        if ($null -eq $unit) { continue }
        if ($unit -and $unit -ne $lastUnit) {
            $lastUnit = $unit
            $key = "$Kind|$($unit.ToLowerInvariant())"
            if (-not $seen.ContainsKey($key)) {
                $seen[$key] = @{ Label = $Label; Unit = $unit }
                $keepUnit = $true
            } elseif ($seen[$key].Label -ceq $Label -and $seen[$key].Unit -ceq $unit) {
                $keepUnit = $true
            } else {
                $keepUnit = $false
                $script:duplicates++
                $w = $seen[$key]
                LogError "Duplicate $Kind name: $unit in $Label ($(Join-Path $SrcDir $unit)) skipped; kept $($w.Unit) from $($w.Label) (first source wins)"
                Write-Summary "ERROR" $tool (Get-ShortDetail "${unit}: dup in $Label")
            }
        }
        if ($unit -and -not $keepUnit) { continue }
        $relNative = $rel -replace '/', [IO.Path]::DirectorySeparatorChar
        $src = Join-Path $SrcDir $relNative
        if (-not (Test-Path -LiteralPath $src -PathType Leaf)) {
            LogWarn "Source ${Label}: $rel is tracked but missing on disk -- skipped"
            continue
        }
        $plan.Add([pscustomobject]@{ Kind = $Kind; Src = $src; Dest = (Join-Path $DestDir $relNative); Item = "$Kind/$rel" })
        $n++
    }
    LogDetail "source ${Label}: $n file(s) planned"
}

Add-Source -Kind "reference"  -Label "reference"      -SrcDir (Join-Path $repoDir "reference")                    -DestDir (Join-Path $harnessDir "reference")  -Layout "tree"
Add-Source -Kind "registries" -Label "registries"     -SrcDir (Join-Path $repoDir "registries")                   -DestDir (Join-Path $harnessDir "registries") -Layout "tree"
Add-Source -Kind "hooks"      -Label "shared/hooks"   -SrcDir (Join-Path (Join-Path $repoDir "shared") "hooks")   -DestDir (Join-Path $harnessDir "hooks")      -Layout "flat"
Add-Source -Kind "hooks"      -Label ".claude/hooks"  -SrcDir (Join-Path (Join-Path $repoDir ".claude") "hooks")  -DestDir (Join-Path $harnessDir "hooks")      -Layout "flat"
Add-Source -Kind "skills"     -Label "shared/skills"  -SrcDir (Join-Path (Join-Path $repoDir "shared") "skills")  -DestDir (Join-Path $harnessDir "skills")     -Layout "units"
Add-Source -Kind "skills"     -Label ".claude/skills" -SrcDir (Join-Path (Join-Path $repoDir ".claude") "skills") -DestDir (Join-Path $harnessDir "skills")     -Layout "units"
Add-Source -Kind "rules"      -Label "shared/rules"   -SrcDir (Join-Path (Join-Path $repoDir "shared") "rules")   -DestDir (Join-Path $harnessDir "rules")      -Layout "flat-md"
Add-Source -Kind "rules"      -Label ".claude/rules"  -SrcDir (Join-Path (Join-Path $repoDir ".claude") "rules")  -DestDir (Join-Path $harnessDir "rules")      -Layout "flat-md"
if ($dotprofile) {
    Add-Source -Kind "rules"  -Label "dotprofile"        -SrcDir (Join-Path (Join-Path $dotprofile "claude") "rules")  -DestDir (Join-Path $harnessDir "rules")  -Layout "flat-md"
    Add-Source -Kind "skills" -Label "dotprofile/skills" -SrcDir (Join-Path (Join-Path $dotprofile "claude") "skills") -DestDir (Join-Path $harnessDir "skills") -Layout "units"
}
# bin: the harness Python CLIs (the list aitools-install's ~/.aitools/bin step deploys)
foreach ($cli in @("harness-db.py", "read-session.py", "read-session-full.py")) {
    $cliSrc = Join-Path $scriptDir $cli
    if (Test-Path -LiteralPath $cliSrc -PathType Leaf) {
        $plan.Add([pscustomobject]@{ Kind = "bin"; Src = $cliSrc; Dest = (Join-Path (Join-Path $harnessDir "bin") $cli); Item = "bin/$cli" })
    } else {
        LogWarn "bin: $cli not found at $cliSrc -- skipped"
    }
}

# =========================================================================
# 5. Deploy every planned file
# =========================================================================
$nAdded = 0; $nUpdated = 0; $nVerified = 0; $nAccepted = 0; $nSkipped = 0; $nFailed = 0
$nWouldCreate = 0; $nWouldUpdate = 0

foreach ($p in $plan) {
    try {
        $content = "$(Get-Content -LiteralPath $p.Src -Raw -ErrorAction Stop)"
    } catch {
        LogError "Failed: $($p.Item): cannot read $($p.Src): $_"
        $nFailed++
        Write-Summary "DETAIL" $tool (Get-ShortDetail "failed: $($p.Item)")
        continue
    }
    if ($DryRun) {
        # Count what the library's dry run reports (same newline normalization).
        if (-not (Test-Path -LiteralPath $p.Dest -PathType Leaf)) {
            $nWouldCreate++
        } else {
            try {
                $cur = "$(Get-Content -LiteralPath $p.Dest -Raw -ErrorAction Stop)"
            } catch {
                LogWarn "Cannot read $($p.Dest) for the dry-run comparison: $_"
                $cur = $null
            }
            if ($null -eq $cur -or ($cur -replace '[\r\n]+$', '') -cne ($content -replace '[\r\n]+$', '')) { $nWouldUpdate++ }
        }
    }
    # Not inside a pipeline or job: [x]abort exits 2 from the library.
    $result = Deploy-ManagedFile -Content $content -DestPath $p.Dest -ToolName $tool -ItemName $p.Item -AdoptPath $p.Src
    if ($result -is [array]) { $result = $result[-1] }   # the result is the last output
    switch ($result) {
        "created"  { $nAdded++ }
        "updated"  { $nUpdated++ }
        "verified" { $nVerified++ }
        "accept & adopt" {
            # The library wrote the adopt target and WARNs when it is a protected file.
            $nAccepted++
            Write-Summary "DETAIL" $tool (Get-ShortDetail "accept & adopt: $($p.Item)")
        }
        "skipped" {
            $nSkipped++
            Write-Summary "DETAIL" $tool (Get-ShortDetail "skipped: $($p.Item)")
        }
        "failed" {
            # The library logged the reason with LogError and restored the files.
            $nFailed++
            Write-Summary "DETAIL" $tool (Get-ShortDetail "failed: $($p.Item)")
        }
        default {
            LogError "Failed: $($p.Item): unexpected deploy result '$result'"
            $nFailed++
            Write-Summary "DETAIL" $tool (Get-ShortDetail "failed: $($p.Item)")
        }
    }
}

# =========================================================================
# 5b. Rules manifest and skills manifest, retired rules and skills
# =========================================================================
# .aitools\rules\.aitools-rules-manifest and .aitools\skills\.aitools-skills-manifest.
# The fan-out consumers (setup-user-claude, setup-user-cursor) read them for each
# name's source and for the names to retire. Format v1, one per kind: UTF-8, LF,
# first line "# aitools <kind> manifest v1", then "<name><TAB><source>" sorted by
# name (ordinal); name = a rule's file name or a skill's directory name, as
# found on disk; source: shared (aitools shared/<kind>), aitools (aitools
# .claude/<kind>), dotprofile (dotprofile claude/<kind>), retired. The source is
# the one that won (first source wins). The rules manifest has no .md extension
# (consumers that copy *.md never copy it); the skills manifest is a file, not a
# directory (consumers that copy skill directories never copy it).
# Retired: a name in the previous manifest that no source has this run (names
# compared case-insensitively). Only a source of the same kind listed this run
# can retire its names; a name whose source was not listed (not found, not a git
# checkout, ls-files failed, no dotprofile) keeps its line. A retired rule's file
# is backed up and removed; a retired skill's directory is copied to
# <name>.bak.<UTC>, the copy verified, then removed (on every run while it is
# there); the line stays until a source has the name again. No previous
# manifest (first run): nothing is retired. A previous manifest with another
# header: warning, nothing retired, rewritten. Same outcomes as deploy-harness.sh.
$rulesManifestHeader = "# aitools rules manifest v1"
$skillsManifestHeader = "# aitools skills manifest v1"
$nRetired = 0

# Get-HarnessManifestPlan KIND HEADER PREV -- from $seen (the winners of KIND),
# $listed and the previous manifest PREV (may be absent): @{ Lines = sorted
# manifest lines; Actions = list of @{ Kind = retire|stale|keep|warn; Name; Extra } }.
# KIND: rules | skills. Throws on a read failure.
function Get-HarnessManifestPlan([string]$Kind, [string]$Header, [string]$Prev) {
    $labels = @{
        "rules"  = @{ "shared/rules" = "shared"; ".claude/rules" = "aitools"; "dotprofile" = "dotprofile" }
        "skills" = @{ "shared/skills" = "shared"; ".claude/skills" = "aitools"; "dotprofile/skills" = "dotprofile" }
    }
    if (-not $labels.ContainsKey($Kind)) { throw "unknown manifest kind: $Kind" }
    $sourceOf = $labels[$Kind]
    $labelOf = @{}
    foreach ($l in $sourceOf.Keys) { $labelOf[$sourceOf[$l]] = $l }
    # The manifest's name rule per kind (as the .sh): rules "<name>.md" (extension any case), skills no
    # leading "."; neither a "/" or "\" nor ".bak.".
    $namePattern = if ($Kind -eq "rules") { '\A[^/\\]+\.[mM][dD]\z' } else { '\A[^/\\.][^/\\]*\z' }
    $lines = [System.Collections.Generic.Dictionary[string, string]]::new([StringComparer]::Ordinal)
    $claimed = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    $actions = [System.Collections.Generic.List[object]]::new()
    foreach ($k in @($seen.Keys)) {
        if (-not $k.StartsWith("$Kind|")) { continue }
        $w = $seen[$k]
        if (-not $sourceOf.ContainsKey($w.Label)) { throw "unknown $Kind source label: $($w.Label)" }
        $lines[$w.Unit] = $sourceOf[$w.Label]
        [void]$claimed.Add($w.Unit)
    }
    if (Test-Path -LiteralPath $Prev -PathType Leaf) {
        $prevLines = [IO.File]::ReadAllLines($Prev, [System.Text.UTF8Encoding]::new($false))
        if ($prevLines.Count -eq 0 -or $prevLines[0] -cne $Header) {
            $actions.Add(@{ Kind = "warn"; Name = "the first line is not `"$Header`" -- nothing retired this run"; Extra = "" })
        } else {
            foreach ($l in ($prevLines | Select-Object -Skip 1)) {
                if ($l -eq "") { continue }
                $parts = $l -split "`t", 2
                $name = $parts[0]
                $src = if ($parts.Count -gt 1) { $parts[1] } else { "" }
                if ($name -cnotmatch $namePattern -or $name -like '*.bak.*' -or
                        $src -cnotmatch '\A(?:shared|aitools|dotprofile|retired)\z') {
                    $actions.Add(@{ Kind = "warn"; Name = "line ignored: $($l -replace "`t", '<TAB>')"; Extra = "" })
                    continue
                }
                if ($claimed.Contains($name)) { continue }          # a source has it this run
                if ($src -ceq "retired") {
                    $lines[$name] = "retired"
                    $actions.Add(@{ Kind = "stale"; Name = $name; Extra = "" })
                } elseif ($listed.ContainsKey("$Kind|$($labelOf[$src])")) {
                    $lines[$name] = "retired"
                    $actions.Add(@{ Kind = "retire"; Name = $name; Extra = $src })
                } else {
                    $lines[$name] = $src
                    $actions.Add(@{ Kind = "keep"; Name = $name; Extra = $src })
                }
            }
        }
    }
    $names = [string[]]@($lines.Keys)
    [Array]::Sort($names, [StringComparer]::Ordinal)
    $out = [System.Collections.Generic.List[string]]::new()
    foreach ($n in $names) { $out.Add("$n`t$($lines[$n])") }
    return @{ Lines = $out; Actions = $actions }
}

# Remove-RetiredRule NAME -- back up and remove .aitools\rules\NAME (a retired rule)
function Remove-RetiredRule([string]$Name) {
    $f = Join-Path (Join-Path $harnessDir "rules") $Name
    if ($DryRun) {
        $script:nWouldRetire++
        Log "[DRY RUN] Would back up and remove $f (retired rule)"
        return
    }
    # Not Backup-File: it resolves wildcards ([ ] in a rule name), finds nothing
    # and reports success. Same name as backup_file: <file>.bak.<UTC timestamp>.
    $bak = "$f.bak." + (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHHmmssZ")
    $backupOk = $true
    try {
        Copy-Item -LiteralPath $f -Destination $bak -Force -ErrorAction Stop
    } catch {
        $backupOk = $false
        LogDetail "Retired rule ${Name}: backup copy failed: $_"
    }
    if (-not $backupOk -or -not (Test-Path -LiteralPath $bak -PathType Leaf)) {
        LogError "Retired rule ${Name}: backup failed -- $f not removed"
        Write-Summary "ERROR" $tool (Get-ShortDetail "retire failed: $Name")
        return
    }
    Log "Backed up $f"
    try {
        Remove-Item -LiteralPath $f -Force -ErrorAction Stop
    } catch {
        LogError "Retired rule ${Name}: cannot remove ${f}: $_"
        Write-Summary "ERROR" $tool (Get-ShortDetail "retire failed: $Name")
        return
    }
    $script:nRetired++
    Log "Removed $f (retired rule; backup kept)"
    Write-Summary "DETAIL" $tool (Get-ShortDetail "retired: rules/$Name")
}

# $skillBackupsKeep -- backups kept per retired skill name (as Backup-Dir keeps 5)
$skillBackupsKeep = 5
$nWouldRetire = 0

# Remove-OldSkillBackups NAME -- keep the newest $skillBackupsKeep <NAME>.bak.<UTC>
# directories beside .aitools\skills\NAME, remove the older ones. Names are
# compared literally (a skill named with [ ] * ? never matches another's
# backups). The retirement is done by then: a failure here is a warning.
function Remove-OldSkillBackups([string]$Name) {
    $skillsDir = Join-Path $harnessDir "skills"
    $prefix = "$Name.bak."
    try {
        $found = @(Get-ChildItem -LiteralPath $skillsDir -Directory -Force -ErrorAction Stop |
            Where-Object {
                $_.Name.StartsWith($prefix, [StringComparison]::Ordinal) -and -not $_.LinkType -and
                $_.Name.Substring($prefix.Length) -cmatch '\A\d{4}-\d\d-\d\dT\d{6}Z\z'
            } | ForEach-Object { $_.Name })
    } catch {
        LogWarn "Retired skill ${Name}: cannot list old backups: $_"
        return
    }
    $names = [string[]]$found
    [Array]::Sort($names, [StringComparer]::Ordinal)
    for ($i = 0; $i -lt $names.Count - $skillBackupsKeep; $i++) {
        $old = Join-Path $skillsDir $names[$i]
        try {
            Remove-SkillTree $old
        } catch {
            LogDetail "Retired skill ${Name}: prune of $old failed: $_"
        }
        if (Test-Path -LiteralPath $old) {
            LogWarn "Retired skill ${Name}: cannot prune old backup $old"
        } else {
            Log "Pruned old backup: $old"
        }
    }
}

# Copy-SkillTree SRC DEST -- copy directory SRC to the new directory DEST, every
# file and subdirectory. .NET calls, not Copy-Item / Remove-Item -Recurse: the
# cmdlets treat a name with [ ] * ? as a wildcard when recursing. Throws on the
# first failure (DEST may then be incomplete; the caller removes it).
function Copy-SkillTree([string]$Src, [string]$Dest) {
    $s = [IO.Path]::GetFullPath($Src).TrimEnd([IO.Path]::DirectorySeparatorChar)
    [void][IO.Directory]::CreateDirectory($Dest)
    foreach ($dir in [IO.Directory]::GetDirectories($s, "*", [IO.SearchOption]::AllDirectories)) {
        [void][IO.Directory]::CreateDirectory((Join-Path $Dest $dir.Substring($s.Length + 1)))
    }
    foreach ($file in [IO.Directory]::GetFiles($s, "*", [IO.SearchOption]::AllDirectories)) {
        [IO.File]::Copy($file, (Join-Path $Dest $file.Substring($s.Length + 1)), $false)
    }
}

# Remove-SkillTree DIR -- delete directory DIR and everything in it (.NET, see
# Copy-SkillTree). Throws on failure.
function Remove-SkillTree([string]$Dir) {
    [IO.Directory]::Delete([IO.Path]::GetFullPath($Dir), $true)
}

# Remove-SkillBackupCopy NAME BAK -- remove an incomplete or unproven backup BAK
function Remove-SkillBackupCopy([string]$Name, [string]$Bak) {
    if (-not (Test-Path -LiteralPath $Bak)) { return }
    # File.Copy keeps the ReadOnly attribute (Windows): Directory.Delete would then
    # fail. Clear it first (the .sh runs chmod -R u+w).
    try {
        foreach ($f in [IO.Directory]::GetFiles([IO.Path]::GetFullPath($Bak), "*", [IO.SearchOption]::AllDirectories)) {
            $attr = [IO.File]::GetAttributes($f)
            if ($attr -band [IO.FileAttributes]::ReadOnly) {
                [IO.File]::SetAttributes($f, $attr -band (-bnot [IO.FileAttributes]::ReadOnly))
            }
        }
    } catch {
        LogWarn "Retired skill ${Name}: cannot make the incomplete backup writable ($_)"
    }
    try {
        Remove-SkillTree $Bak
    } catch {
        LogDetail "Retired skill ${Name}: removing the incomplete backup failed: $_"
    }
    if (-not (Test-Path -LiteralPath $Bak)) {
        Log "Retired skill ${Name}: removed the incomplete backup $Bak"
        return
    }
    # Still there: rename it to <name>.bak.incomplete.<UTC>. The prune counts only
    # <name>.bak.<UTC>, so it never counts this one; ".bak." keeps the fan-out
    # and the deploy from treating it as a skill.
    $inc = Join-Path (Join-Path $harnessDir "skills") ("$Name.bak.incomplete." + (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHHmmssZ"))
    $renamed = $false
    if (-not (Test-Path -LiteralPath $inc)) {
        try {
            [IO.Directory]::Move([IO.Path]::GetFullPath($Bak), $inc)
            $renamed = $true
        } catch {
            LogDetail "Retired skill ${Name}: renaming the incomplete backup failed: $_"
        }
    }
    if ($renamed) {
        LogError "Retired skill ${Name}: cannot remove the incomplete backup -- renamed to $inc; delete it by hand"
    } else {
        LogError "Retired skill ${Name}: cannot remove or rename the incomplete backup $Bak; delete it by hand"
    }
    Write-Summary "ERROR" $tool (Get-ShortDetail "bak cleanup failed: $Name")
}

# Get-TreeDifference A B -- "" when directories A and B hold the same relative
# file paths with the same bytes, else the first difference. Throws on a read
# failure.
function Get-TreeDifference([string]$A, [string]$B) {
    # .NET enumeration, not Get-ChildItem -LiteralPath -Recurse: that treats a leaf
    # name with [ ] * ? as a wildcard and lists sibling directories too.
    $list = {
        param($root)
        $full = [IO.Path]::GetFullPath($root).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
        $rels = @([IO.Directory]::GetFiles($full, "*", [IO.SearchOption]::AllDirectories) |
            ForEach-Object { $_.Substring($full.Length) })
        $arr = [string[]]$rels
        [Array]::Sort($arr, [StringComparer]::Ordinal)
        return ,$arr
    }
    $ra = & $list $A
    $rb = & $list $B
    $sb = [System.Collections.Generic.HashSet[string]]::new([string[]]$rb, [StringComparer]::Ordinal)
    foreach ($r in $ra) { if (-not $sb.Contains($r)) { return "Only in ${A}: $r" } }
    $sa = [System.Collections.Generic.HashSet[string]]::new([string[]]$ra, [StringComparer]::Ordinal)
    foreach ($r in $rb) { if (-not $sa.Contains($r)) { return "Only in ${B}: $r" } }
    foreach ($r in $ra) {
        $ha = (Get-FileHash -LiteralPath (Join-Path $A $r) -Algorithm SHA256 -ErrorAction Stop).Hash
        $hb = (Get-FileHash -LiteralPath (Join-Path $B $r) -Algorithm SHA256 -ErrorAction Stop).Hash
        if ($ha -ne $hb) { return "Files $(Join-Path $A $r) and $(Join-Path $B $r) differ" }
    }
    return ""
}

# Remove-RetiredSkill NAME -- copy .aitools\skills\NAME to NAME.bak.<UTC>
# (Copy-Item -Recurse; any skill directory, no *.md precondition), verify the copy
# holds the same files, then remove NAME (a retired skill) and prune old
# backups. A failed or unproven copy is removed again and NAME is kept (ERROR
# row; the next run retries). Same outcomes as retire_skill_dir in the .sh.
function Remove-RetiredSkill([string]$Name) {
    $skillsDir = Join-Path $harnessDir "skills"
    $d = Join-Path $skillsDir $Name
    if ($DryRun) {
        $script:nWouldRetire++
        Log "[DRY RUN] Would back up and remove $d (retired skill)"
        return
    }
    $bak = "$d.bak." + (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHHmmssZ")
    if (Test-Path -LiteralPath $bak) {
        LogError "Retired skill ${Name}: backup failed ($bak already exists) -- $d not removed"
        Write-Summary "ERROR" $tool (Get-ShortDetail "retire failed: $Name")
        return
    }
    try {
        Copy-SkillTree $d $bak
    } catch {
        LogError "Retired skill ${Name}: backup failed ($_) -- $d not removed"
        Write-Summary "ERROR" $tool (Get-ShortDetail "retire failed: $Name")
        Remove-SkillBackupCopy $Name $bak
        return
    }
    try {
        $diff = Get-TreeDifference $d $bak
    } catch {
        $diff = "comparison failed: $_"
    }
    if ($diff) {
        LogError "Retired skill ${Name}: backup $bak differs from the directory ($diff) -- $d not removed"
        Write-Summary "ERROR" $tool (Get-ShortDetail "retire failed: $Name")
        Remove-SkillBackupCopy $Name $bak
        return
    }
    try {
        Remove-SkillTree $d
    } catch {
        LogDetail "Retired skill ${Name}: removal failed: $_"
    }
    if (Test-Path -LiteralPath $d) {
        LogError "Retired skill ${Name}: cannot remove $d"
        Write-Summary "ERROR" $tool (Get-ShortDetail "retire failed: $Name")
        return
    }
    $script:nRetired++
    Log "Removed $d (retired skill; backup $bak)"
    Write-Summary "DETAIL" $tool (Get-ShortDetail "retired: skills/$Name")
    Remove-OldSkillBackups $Name
}

# Write-HarnessManifest KIND -- section 5b for one kind (rules | skills): retire,
# then write the manifest (temp file + move)
function Write-HarnessManifest([string]$Kind) {
    if ($Kind -eq "rules") {
        $header = $rulesManifestHeader; $title = "Rules"; $noun = "rule"
    } else {
        $header = $skillsManifestHeader; $title = "Skills"; $noun = "skill"
    }
    $kindDir = Join-Path $harnessDir $Kind
    $manifest = Join-Path $kindDir ".aitools-$Kind-manifest"
    $tmp = "$manifest.tmp"
    try {
        $mp = Get-HarnessManifestPlan $Kind $header $manifest
    } catch {
        LogError "$title manifest: $_ -- manifest not written, nothing retired"
        Write-Summary "ERROR" $tool "$Kind manifest not written"
        return
    }
    foreach ($a in $mp.Actions) {
        switch ($a.Kind) {
            "warn" { LogWarn "$title manifest ${manifest}: $($a.Name)" }
            "keep" { Log "$title manifest: $($a.Name) kept as $($a.Extra) (source not listed this run -- not retired)" }
            { $_ -in @("retire", "stale") } {
                if ($a.Kind -eq "retire") {
                    $dry = if ($DryRun) { "[DRY RUN] " } else { "" }
                    Log "${dry}Retired ${noun}: $($a.Name) (was $($a.Extra); no source has it now)"
                }
                $p = Join-Path $kindDir $a.Name
                if ($Kind -eq "rules") {
                    # A file (or a symlink to one), as the .sh's -f / -L; never a directory
                    if (Test-Path -LiteralPath $p -PathType Leaf) { Remove-RetiredRule $a.Name }
                } else {
                    $item = $null
                    try {
                        $item = Get-Item -LiteralPath $p -Force -ErrorAction Stop
                    } catch [System.Management.Automation.ItemNotFoundException] {
                        $item = $null   # absent: nothing to remove (the common case)
                    } catch {
                        LogWarn "Retired skill $($a.Name): cannot read ${p}: $_ -- left alone"
                        Write-Summary "WARN" $tool (Get-ShortDetail "cannot read: $($a.Name)")
                        continue
                    }
                    if ($null -eq $item) {
                        # absent: nothing to remove
                    } elseif ($item.PSIsContainer -and -not $item.LinkType) {
                        Remove-RetiredSkill $a.Name
                    } else {
                        LogWarn "Retired skill $($a.Name): $p is not a directory -- left alone"
                        Write-Summary "WARN" $tool (Get-ShortDetail "not a dir: $($a.Name)")
                    }
                }
            }
        }
    }
    $n = $mp.Lines.Count
    if ($DryRun) {
        Log "[DRY RUN] Would write $manifest ($n $noun line(s))"
        return
    }
    # A directory at the manifest path: same outcome as the .sh (File.Move would
    # also fail, with a less clear message).
    if (Test-Path -LiteralPath $manifest -PathType Container) {
        LogError "$title manifest: $manifest is a directory -- manifest not written"
        Write-Summary "ERROR" $tool "$Kind manifest not written"
        return
    }
    $text = "$header`n"
    foreach ($l in $mp.Lines) { $text += "$l`n" }
    try {
        [IO.File]::WriteAllText($tmp, $text, [System.Text.UTF8Encoding]::new($false))
        [IO.File]::Move($tmp, $manifest, $true)
    } catch {
        LogError "$title manifest: cannot write ${manifest}: $_ -- manifest not written"
        Write-Summary "ERROR" $tool "$Kind manifest not written"
        if (Test-Path -LiteralPath $tmp) {
            try { Remove-Item -LiteralPath $tmp -Force -ErrorAction Stop } catch { LogWarn "Cannot remove ${tmp}: $_" }
        }
        return
    }
    Log "$title manifest: wrote $manifest ($n $noun line(s))"
}

