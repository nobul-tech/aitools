    }
    $dFull = [IO.Path]::GetFullPath($d).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    foreach ($f in $found) {
        $rel = [IO.Path]::GetFullPath($f.FullName).Substring($dFull.Length)
        # A backup (a *.bak.* file, or any file in a *.bak.* directory such as a
