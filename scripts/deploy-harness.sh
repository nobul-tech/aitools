#!/usr/bin/env bash
# deploy-harness.sh -- populate ~/.aitools, the deployed harness, from the repos (macOS/Linux)
#
# Creates ~/.aitools/{reference,registries,hooks,rules,skills,bin}, deploys every
# source file into it through deploy_managed_file (summary tool "harness files",
# adopt target = the repo file), and generates ~/.aitools/config.json from
# profile.json by calling the only config writer, setup-user-config.sh.
#
# Safe to re-run: a file equal to its source is verified and not written.
# Platform: macOS/Linux. On Windows use deploy-harness.ps1.
# Reference: reference/harness.md "Deployed harness (~/.aitools)" (sources,
#   conflict handling, assumptions); managed tools: none installed here
#   (/tool-registry skill).
#
# Managed (each file through deploy_managed_file; git-tracked source files only):
#   ~/.aitools/reference/**        <- <aitools>/reference/**
#   ~/.aitools/registries/**       <- <aitools>/registries/**
#   ~/.aitools/hooks/<file>        <- <aitools>/shared/hooks, then <aitools>/.claude/hooks (flat)
#   ~/.aitools/skills/<name>/**    <- <aitools>/shared/skills, then <aitools>/.claude/skills
#   ~/.aitools/rules/<file>.md     <- <aitools>/shared/rules, <aitools>/.claude/rules,
#                                     <dotprofile>/claude/rules (one flat directory)
#   ~/.aitools/bin/<cli>           <- <aitools>/scripts/{harness-db.py,read-session.py,read-session-full.py}
#   ~/.aitools/config.json         <- generated by setup-user-config.sh (its own managed fields)
# Name conflicts: the first source wins; each skipped duplicate is log_error +
#   an ERROR row. Unit: file name (rules, hooks), skill directory name (skills);
#   compared case-insensitively. Files named *.bak.* are never deployed.
# Preserved: every other file under ~/.aitools (logs, backups, files with no
#   source -- each logged, never deleted).
# Overwrites: no -- a deployed file that differs from its source gets the review menu.
#
# Usage: deploy-harness.sh [--dry-run] [--force] [--help]
#   --dry-run   report what would change; write nothing (also AITOOLS_DRY_RUN=1)
#   --force     no review menu: source wins (also AITOOLS_FORCE=1)
# Exit: 0 done (warnings possible), 1 errors (incl. duplicates, config.json
#   not generated), 2 aborted by the user at a review menu.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/aitools-lib.sh"
logging_init "deploy-harness"

# --- OS guard ---
case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*)
        log_error "This script is for macOS/Linux. On Windows, use deploy-harness.ps1."
        exit 1 ;;
esac

TOOL="harness files"

usage() {
    # The header comment (line 2 to the first non-comment line), "# " removed.
    perl -ne 'next if $. == 1; last unless /^#/; s/^# ?//; print' "$SCRIPT_DIR/deploy-harness.sh"
}

# --- Flags ---
DRY_RUN=false
FORCE=false
if [ "${AITOOLS_DRY_RUN:-}" = "1" ]; then DRY_RUN=true; fi
if [ "${AITOOLS_FORCE:-}" = "1" ]; then FORCE=true; fi
while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run) DRY_RUN=true ;;
        --force)   FORCE=true ;;
        --help|-h) usage; exit 0 ;;
        *)
            log_error "Unknown option: $1 (see --help)"
            write_summary ERROR "$TOOL" "bad arguments"
            exit 1 ;;
    esac
    shift
done
# The library reads FORCE=true / AITOOLS_FORCE=1; the config writer inherits it.
if $FORCE; then export AITOOLS_FORCE=1; fi
if $DRY_RUN; then log "[DRY RUN] Preview mode -- no files will be written"; fi

REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
HARNESS_DIR="$HOME/.aitools"

if ! WORK=$(mktemp -d); then
    log_error "Could not create a work directory -- nothing deployed"
    write_summary ERROR "$TOOL" "no work directory"
    exit 1
fi
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

# short TEXT -- a summary detail of at most 30 characters (script-standards).
short() {
    local s="$1"
    if [ "${#s}" -gt 30 ]; then s="${s:0:27}..."; fi
    printf '%s' "$s"
}

# =========================================================================
# 1. config.json -- generated from profile.json by the only writer
# =========================================================================
CONFIG_WRITER="$SCRIPT_DIR/setup-user-config.sh"
if [ ! -f "$CONFIG_WRITER" ]; then
    log_error "config.json: writer not found at $(display_path "$CONFIG_WRITER") -- config.json not generated"
    write_summary ERROR "$TOOL" "config.json not generated"
else
    log "config.json: generating from profile.json (setup-user-config.sh)"
    CW_RC=0
    if $DRY_RUN; then
        "${BASH:-bash}" "$CONFIG_WRITER" --dry-run || CW_RC=$?
    else
        "${BASH:-bash}" "$CONFIG_WRITER" || CW_RC=$?
    fi
    if [ "$CW_RC" -ne 0 ]; then
        log_error "config.json: setup-user-config.sh failed (exit $CW_RC) -- see its log lines above"
        write_summary ERROR "$TOOL" "config.json not generated"
    fi
fi

# =========================================================================
# 2. Dotprofile (source of user rules): userRepoPath in config.json
# =========================================================================
DOTPROFILE=""
# read_config_key returns 1 when the file or the key is absent: handled below.
URP=$(read_config_key "$HARNESS_DIR/config.json" "userRepoPath") || URP=""
if [ -z "$URP" ]; then
    log "No userRepoPath in $(display_path "$HARNESS_DIR/config.json") -- dotprofile rules skipped (run: aitools user init)"
elif [ ! -d "$URP" ]; then
    log "Dotprofile $(display_path "$URP") not found -- dotprofile rules skipped"
else
    DOTPROFILE="$URP"
fi

# =========================================================================
# 3. The six directories
# =========================================================================
KINDS="reference registries hooks rules skills bin"
for kind in $KINDS; do
    d="$HARNESS_DIR/$kind"
    if [ -d "$d" ]; then continue; fi
    if $DRY_RUN; then
        log "[DRY RUN] Would create $(display_path "$d")"
    elif mkdir -p "$d"; then
        log "Created $(display_path "$d")"
    else
        log_error "Cannot create $(display_path "$d")"
        write_summary ERROR "$TOOL" "$(short "cannot create $kind/")"
    fi
done

# =========================================================================
# 4. Plan: every source file, conflicts resolved (first source wins)
# =========================================================================
PLAN="$WORK/plan.tsv"     # kind <TAB> source <TAB> dest <TAB> item
SEEN="$WORK/seen.tsv"     # kind <TAB> lowercased unit <TAB> source label <TAB> unit
: > "$PLAN"
: > "$SEEN"
DUPLICATES=0

# seen_winner KIND KEY -- "label<TAB>unit" of the source that claimed KEY first; "" when none
seen_winner() {
    perl -e '
        my ($f, $kind, $key) = @ARGV;
        open my $h, "<", $f or die "cannot read $f: $!\n";
        while (my $l = <$h>) {
            chomp $l;
            my @a = split /\t/, $l, 4;
            if ($a[0] eq $kind && $a[1] eq $key) { print "$a[2]\t$a[3]"; exit 0; }
        }
    ' "$SEEN" "$1" "$2"
}

# add_source KIND LABEL SRC_DIR DEST_DIR LAYOUT
#   LAYOUT tree   : every file, relative paths kept, no conflicts (reference, registries)
#          flat   : top-level files only; unit = file name (hooks)
#          flat-md: top-level *.md files only; unit = file name (rules)
#          units  : files inside top-level directories; unit = directory name (skills)
add_source() {
    local kind="$1" label="$2" src_dir="$3" dest_dir="$4" layout="$5"
    if [ ! -d "$src_dir" ]; then
        log "Source $label not found ($(display_path "$src_dir")) -- skipped"
        return 0
    fi
    # 2>/dev/null: rev-parse fails outside a git work tree; that failure is the answer.
    if ! git -C "$src_dir" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        log_error "Source $label ($(display_path "$src_dir")) is not in a git work tree -- skipped (only git-tracked files are deployed)"
        write_summary ERROR "$TOOL" "$(short "$label: not a git checkout")"
        return 0
    fi
    local ls="$WORK/ls.z"
    if ! git -C "$src_dir" ls-files -z > "$ls" 2> "$WORK/ls.err"; then
        log_error "Source $label: git ls-files failed in $(display_path "$src_dir"): $(cat "$WORK/ls.err")"
        write_summary ERROR "$TOOL" "$(short "$label: git ls-files failed")"
        return 0
    fi
    local rel base unit lc winner w_label w_unit last_unit="" keep_unit=true n=0
    while IFS= read -r -d '' rel <&4; do
        base="${rel##*/}"
        case "$base" in
            *.bak.*) log_detail "skip backup copy: $label/$rel"; continue ;;
        esac
        unit=""
        case "$layout" in
            flat|flat-md)
                case "$rel" in
                    */*) log_detail "skip nested file in a flat source: $label/$rel"; continue ;;
                esac
                if [ "$layout" = "flat-md" ]; then
                    case "$rel" in
                        *.md) ;;
                        *) log_detail "skip non-.md file in a rules source: $label/$rel"; continue ;;
                    esac
                fi
                unit="$rel" ;;
            units)
                case "$rel" in
                    */*) unit="${rel%%/*}" ;;
                    *) log_detail "skip file outside a skill directory: $label/$rel"; continue ;;
                esac ;;
        esac
        if [ -n "$unit" ] && [ "$unit" != "$last_unit" ]; then
            last_unit="$unit"
            lc=$(printf '%s' "$unit" | tr '[:upper:]' '[:lower:]')
            if ! winner=$(seen_winner "$kind" "$lc"); then
                log_error "Source $label: conflict lookup failed for $unit -- skipped"
                keep_unit=false
                continue
            fi
            if [ -z "$winner" ]; then
                printf '%s\t%s\t%s\t%s\n' "$kind" "$lc" "$label" "$unit" >> "$SEEN"
                keep_unit=true
            else
                w_label="${winner%%$'\t'*}"
                w_unit="${winner#*$'\t'}"
                if [ "$w_label" = "$label" ] && [ "$w_unit" = "$unit" ]; then
                    keep_unit=true
                else
                    keep_unit=false
                    DUPLICATES=$((DUPLICATES + 1))
                    log_error "Duplicate $kind name: $unit in $label ($(display_path "$src_dir/$unit")) skipped; kept $w_unit from $w_label (first source wins)"
                    write_summary ERROR "$TOOL" "$(short "$unit: dup in $label")"
                fi
            fi
        fi
        if [ -n "$unit" ] && ! $keep_unit; then continue; fi
        if [ ! -f "$src_dir/$rel" ]; then
            log_warn "Source $label: $rel is tracked but missing on disk -- skipped"
            continue
        fi
        printf '%s\t%s\t%s\t%s\n' "$kind" "$src_dir/$rel" "$dest_dir/$rel" "$kind/$rel" >> "$PLAN"
        n=$((n + 1))
    done 4< "$ls"
    log_detail "source $label: $n file(s) planned"
}

add_source reference  "reference"        "$REPO_DIR/reference"       "$HARNESS_DIR/reference"  tree
add_source registries "registries"       "$REPO_DIR/registries"      "$HARNESS_DIR/registries" tree
add_source hooks      "shared/hooks"     "$REPO_DIR/shared/hooks"    "$HARNESS_DIR/hooks"      flat
add_source hooks      ".claude/hooks"    "$REPO_DIR/.claude/hooks"   "$HARNESS_DIR/hooks"      flat
add_source skills     "shared/skills"    "$REPO_DIR/shared/skills"   "$HARNESS_DIR/skills"     units
add_source skills     ".claude/skills"   "$REPO_DIR/.claude/skills"  "$HARNESS_DIR/skills"     units
add_source rules      "shared/rules"     "$REPO_DIR/shared/rules"    "$HARNESS_DIR/rules"      flat-md
add_source rules      ".claude/rules"    "$REPO_DIR/.claude/rules"   "$HARNESS_DIR/rules"      flat-md
if [ -n "$DOTPROFILE" ]; then
    add_source rules  "dotprofile"       "$DOTPROFILE/claude/rules"  "$HARNESS_DIR/rules"      flat-md
fi
# bin: the harness Python CLIs (the list aitools-install's ~/.aitools/bin step deploys)
for cli in harness-db.py read-session.py read-session-full.py; do
    if [ -f "$SCRIPT_DIR/$cli" ]; then
        printf '%s\t%s\t%s\t%s\n' bin "$SCRIPT_DIR/$cli" "$HARNESS_DIR/bin/$cli" "bin/$cli" >> "$PLAN"
    else
        log_warn "bin: $cli not found at $(display_path "$SCRIPT_DIR/$cli") -- skipped"
    fi
done

# =========================================================================
# 5. Deploy every planned file
# =========================================================================
N_ADDED=0; N_UPDATED=0; N_VERIFIED=0; N_ACCEPTED=0; N_SKIPPED=0; N_FAILED=0
N_WOULD_CREATE=0; N_WOULD_UPDATE=0

# fix_exec SRC DEST -- a deployed copy of an executable source is executable too
fix_exec() {
    if [ -x "$1" ] && [ -f "$2" ] && [ ! -x "$2" ]; then
        if chmod +x "$2"; then
            log "Set executable: $(display_path "$2")"
        else
            log_error "Cannot set the executable bit on $(display_path "$2")"
        fi
    fi
}

# deploy_one SRC DEST ITEM. Not run in a subshell: [x]abort exits 2 from here.
deploy_one() {
    local src="$1" dest="$2" item="$3" content
    if ! content=$(cat "$src"); then
        log_error "Failed: $item: cannot read $(display_path "$src")"
        N_FAILED=$((N_FAILED + 1))
        write_summary DETAIL "$TOOL" "$(short "failed: $item")"
        return 0
    fi
    if $DRY_RUN; then
        # Count what the library's dry run reports (same newline normalization).
        if [ ! -f "$dest" ]; then
            N_WOULD_CREATE=$((N_WOULD_CREATE + 1))
        elif [ "$(perl -0777 -pe 's/[\r\n]+$/\n/' "$dest")" != "$(printf '%s' "$content" | perl -0777 -pe 's/[\r\n]+$/\n/')" ]; then
            N_WOULD_UPDATE=$((N_WOULD_UPDATE + 1))
        fi
    fi
    deploy_managed_file "$content" "$dest" "$TOOL" "$item" "$src"
    case "$MANAGED_FILE_RESULT" in
        created)
            N_ADDED=$((N_ADDED + 1)); fix_exec "$src" "$dest" ;;
        updated)
            N_UPDATED=$((N_UPDATED + 1)); fix_exec "$src" "$dest" ;;
        verified)
            N_VERIFIED=$((N_VERIFIED + 1))
            if ! $DRY_RUN; then fix_exec "$src" "$dest"; fi ;;
        "accept & adopt")
            # The library wrote the adopt target and WARNs when it is a protected file.
            N_ACCEPTED=$((N_ACCEPTED + 1))
            write_summary DETAIL "$TOOL" "$(short "accept & adopt: $item")" ;;
        skipped)
            N_SKIPPED=$((N_SKIPPED + 1))
            write_summary DETAIL "$TOOL" "$(short "skipped: $item")" ;;
        failed)
            # The library logged the reason with log_error and restored the files.
            N_FAILED=$((N_FAILED + 1))
            write_summary DETAIL "$TOOL" "$(short "failed: $item")" ;;
        *)
            log_error "Failed: $item: unexpected deploy result '$MANAGED_FILE_RESULT'"
            N_FAILED=$((N_FAILED + 1))
            write_summary DETAIL "$TOOL" "$(short "failed: $item")" ;;
    esac
}

N_PLANNED=0
# fd 3 carries the plan so stdin stays the terminal for the review menu.
while IFS=$'\t' read -r kind src dest item <&3; do
    [ -n "$kind" ] || continue
    N_PLANNED=$((N_PLANNED + 1))
    deploy_one "$src" "$dest" "$item"
done 3< "$PLAN"

# =========================================================================
# 6. Preserved: files under the six directories with no source (logged, kept)
# =========================================================================
N_PRESERVED=0
cut -f3 "$PLAN" > "$WORK/dests.txt"
for kind in $KINDS; do
    d="$HARNESS_DIR/$kind"
    [ -d "$d" ] || continue
    if ! find "$d" -type f > "$WORK/found.txt"; then
        log_warn "Cannot list $(display_path "$d") -- preserved files not checked"
        continue
    fi
    if ! perl -e '
        my ($dests, $found) = @ARGV;
        my %d;
        open my $h, "<", $dests or die "cannot read $dests: $!\n";
        while (<$h>) { chomp; $d{$_} = 1; }
        open my $f, "<", $found or die "cannot read $found: $!\n";
        while (<$f>) {
            chomp;
            my $b = $_; $b =~ s{.*/}{};
            next if $b =~ /\.bak\./;
            print "$_\n" unless $d{$_};
        }
    ' "$WORK/dests.txt" "$WORK/found.txt" > "$WORK/preserved.txt"; then
        log_warn "Cannot compare $(display_path "$d") with the plan -- preserved files not checked"
        continue
    fi
    while IFS= read -r p; do
        [ -n "$p" ] || continue
        N_PRESERVED=$((N_PRESERVED + 1))
        log "Preserved: $(display_path "$p") (no source -- kept)"
    done < "$WORK/preserved.txt"
done

# =========================================================================
# 7. Summary (one row under "harness files") + exit footer
# =========================================================================
log "harness files: $N_PLANNED planned, $N_ADDED added, $N_UPDATED updated, $N_ACCEPTED accepted, $N_VERIFIED verified, $N_SKIPPED skipped, $N_FAILED failed, $N_PRESERVED preserved, $DUPLICATES duplicate(s)"
if $DRY_RUN; then
    write_summary OK "$TOOL" "$(short "dry-run: $N_WOULD_CREATE create, $N_WOULD_UPDATE update")"
elif [ "$N_FAILED" -gt 0 ]; then
    write_summary ERROR "$TOOL" "$(short "$N_FAILED failed")"
elif [ "$N_SKIPPED" -gt 0 ]; then
    write_summary WARN "$TOOL" "$(short "$N_SKIPPED skipped (user review)")"
else
    PARTS=""
    if [ "$N_ADDED" -gt 0 ]; then PARTS="$N_ADDED added"; fi
    if [ "$N_UPDATED" -gt 0 ]; then PARTS="${PARTS:+$PARTS, }$N_UPDATED updated"; fi
    if [ "$N_ACCEPTED" -gt 0 ]; then PARTS="${PARTS:+$PARTS, }$N_ACCEPTED accepted"; fi
    if [ -z "$PARTS" ]; then
        PARTS="$N_VERIFIED verified"
    elif [ "${#PARTS}" -le 18 ] && [ "$N_VERIFIED" -gt 0 ]; then
        PARTS="$PARTS, $N_VERIFIED verified"
    fi
    write_summary OK "$TOOL" "$(short "$PARTS")"
fi

if [ "$ERRORS" -gt 0 ]; then
    log "FAILED with $ERRORS error(s)" "error"
    exit 1
elif [ "$WARNINGS" -gt 0 ]; then
    log "COMPLETED with $WARNINGS warning(s)" "warn"
    exit 0
else
    log "COMPLETED successfully" "ok"
    exit 0
fi
