#!/usr/bin/env bash
# deploy-harness.sh -- populate ~/.aitools, the deployed harness, from the repos (macOS/Linux)
#
# Creates ~/.aitools/{reference,registries,hooks,rules,skills,bin}, deploys every
# source file into it through deploy_managed_file (summary tool "harness files",
# adopt target = the repo file), and generates ~/.aitools/config.json from
# profile.json by calling the only config writer, setup-user-config.sh.
#
# Safe to re-run: a file equal to its source is verified and not written.
# Platform: macOS/Linux. On Windows use deploy-harness.ps1.
# Reference: reference/harness.md "Deployed harness (~/.aitools)" (sources,
#   conflict handling, assumptions); managed tools: none installed here
#   (/tool-registry skill).
#
# --- BEGIN scope (extracted by build-deploy) ---
# Managed (each file through deploy_managed_file; git-tracked source files only):
#   ~/.aitools/reference/**        <- <aitools>/reference/**
#   ~/.aitools/registries/**       <- <aitools>/registries/**
#   ~/.aitools/hooks/<file>        <- <aitools>/shared/hooks, then <aitools>/.claude/hooks (flat)
#   ~/.aitools/skills/<name>/**    <- <aitools>/shared/skills, <aitools>/.claude/skills,
#                                     <dotprofile>/claude/skills (one directory per skill)
#   ~/.aitools/rules/<file>.md     <- <aitools>/shared/rules, <aitools>/.claude/rules,
#                                     <dotprofile>/claude/rules (one flat directory)
#   ~/.aitools/bin/<cli>           <- <aitools>/scripts/{harness-db.py,read-session.py,read-session-full.py}
#   ~/.aitools/config.json         <- generated by setup-user-config.sh (its own managed fields);
#                                     not run with --skip-config (row "config.json n/a")
#   ~/.aitools/rules/.aitools-rules-manifest   <- written every run (sole owner): one
#                                     "<file name><TAB><source>" line per rule (section 5b)
#   ~/.aitools/skills/.aitools-skills-manifest <- written every run (sole owner): one
#                                     "<skill name><TAB><source>" line per skill (section 5b)
#                                     Source: shared | aitools | dotprofile | retired.
# Name conflicts: the first source wins; each skipped duplicate is log_error +
#   an ERROR row. Unit: file name (rules, hooks), skill directory name (skills);
#   compared case-insensitively. Files named *.bak.* are never deployed, nor
#   skill directories whose name starts with "." or contains ".bak.".
# Retired: a rule or skill in the previous manifest that no source has any more
#   (only when its source was listed this run). A retired rule's file is backed
#   up and removed from ~/.aitools/rules; a retired skill's directory is backed
#   up with backup_dir (~/.aitools/skills/<name>.bak.<UTC>/, backup verified)
#   and removed from ~/.aitools/skills. The manifest keeps the "retired" line
#   until a source has the name again.
# Preserved: every other file under ~/.aitools (logs, backups, files with no
#   source -- each logged, never deleted; backups and the manifests are not listed).
# Overwrites: no -- a deployed file that differs from its source gets the review menu.
# --- END scope (extracted by build-deploy) ---
#
# Usage: deploy-harness.sh [--dry-run] [--force] [--skip-config] [--help]
#   --dry-run       report what would change; write nothing (also AITOOLS_DRY_RUN=1)
#   --force         no review menu: source wins (also AITOOLS_FORCE=1)
#   --skip-config   do not run the config writer (the caller already ran it, e.g.
#                   aitools-install Step 5); summary row OK "config.json"
#                   "n/a (written by installer)"
# Exit: 0 done (warnings possible), 1 errors (incl. duplicates, config.json
#   not generated), 2 aborted by the user at a review menu.
# Marker lines ("BEGIN|END <name> (extracted|replaced by build-deploy)") mark
# the spans build-deploy.sh copies into the MDM variant (<dotprofile>/deploy/).

# --- BEGIN body (extracted by build-deploy) ---
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/aitools-lib.sh"
logging_init "deploy-harness"

# --- OS guard ---
case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*)
        log_error "This script is for macOS/Linux. On Windows, use deploy-harness.ps1."
        exit 1 ;;
esac

TOOL="harness files"

usage() {
    # The header comment (line 2 to the first non-comment line), "# " removed;
    # the build-deploy span markers are not shown.
    perl -ne 'next if $. == 1; last unless /^#/; next if /^# --- (?:BEGIN|END) /; s/^# ?//; print' "$SCRIPT_DIR/deploy-harness.sh"
}

# --- Flags ---
DRY_RUN=false
FORCE=false
SKIP_CONFIG=""   # non-empty: the config writer is not run; the reason goes in the summary row
if [ "${AITOOLS_DRY_RUN:-}" = "1" ]; then DRY_RUN=true; fi
if [ "${AITOOLS_FORCE:-}" = "1" ]; then FORCE=true; fi
while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run) DRY_RUN=true ;;
        --force)   FORCE=true ;;
        --skip-config) SKIP_CONFIG="written by installer" ;;
        --help|-h) usage; exit 0 ;;
        *)
            log_error "Unknown option: $1 (see --help)"
            write_summary ERROR "$TOOL" "bad arguments"
            exit 1 ;;
    esac
    shift
done
# The library reads FORCE=true / AITOOLS_FORCE=1; the config writer inherits it.
if $FORCE; then export AITOOLS_FORCE=1; fi
if $DRY_RUN; then log "[DRY RUN] Preview mode -- no files will be written"; fi

REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
HARNESS_DIR="$HOME/.aitools"

if ! WORK=$(mktemp -d); then
    log_error "Could not create a work directory -- nothing deployed"
    write_summary ERROR "$TOOL" "no work directory"
    exit 1
fi
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

# short TEXT -- a summary detail of at most 30 characters (script-standards).
short() {
    local s="$1"
    if [ "${#s}" -gt 30 ]; then s="${s:0:27}..."; fi
    printf '%s' "$s"
}

# =========================================================================
# 1. config.json -- generated from profile.json by the only writer
# =========================================================================
CONFIG_WRITER="$SCRIPT_DIR/setup-user-config.sh"
# --- BEGIN config bootstrap check (replaced by build-deploy) ---
# Dev path: aitools-install writes the bootstrap keys (reposPath, repoPath)
# before any run, so the writer always runs unless --skip-config. The MDM
# variant checks for the keys here and skips the writer without them.
# --- END config bootstrap check (replaced by build-deploy) ---
if [ -n "$SKIP_CONFIG" ]; then
    # One path for --skip-config and the MDM no-bootstrap case: not an error.
    log "config.json: setup-user-config.sh not run ($SKIP_CONFIG)"
    write_summary OK "config.json" "$(short "n/a ($SKIP_CONFIG)")"
elif [ ! -f "$CONFIG_WRITER" ]; then
    log_error "config.json: writer not found at $(display_path "$CONFIG_WRITER") -- config.json not generated"
    write_summary ERROR "$TOOL" "config.json not generated"
else
    log "config.json: generating from profile.json (setup-user-config.sh)"
    CW_RC=0
    if $DRY_RUN; then
        "${BASH:-bash}" "$CONFIG_WRITER" --dry-run || CW_RC=$?
    else
        "${BASH:-bash}" "$CONFIG_WRITER" || CW_RC=$?
    fi
    if [ "$CW_RC" -ne 0 ]; then
        log_error "config.json: setup-user-config.sh failed (exit $CW_RC) -- see its log lines above"
        write_summary ERROR "$TOOL" "config.json not generated"
    fi
fi

# --- BEGIN dotprofile lookup (replaced by build-deploy) ---
# =========================================================================
# 2. Dotprofile (source of user rules and skills): userRepoPath in config.json
# =========================================================================
DOTPROFILE=""
# read_config_key returns 1 when the file or the key is absent: handled below.
URP=$(read_config_key "$HARNESS_DIR/config.json" "userRepoPath") || URP=""
if [ -z "$URP" ]; then
    log "No userRepoPath in $(display_path "$HARNESS_DIR/config.json") -- dotprofile rules and skills skipped (run: aitools user init)"
elif [ ! -d "$URP" ]; then
    log "Dotprofile $(display_path "$URP") not found -- dotprofile rules and skills skipped"
else
    DOTPROFILE="$URP"
fi

# --- END dotprofile lookup (replaced by build-deploy) ---
# =========================================================================
# 3. The six directories
# =========================================================================
KINDS="reference registries hooks rules skills bin"
for kind in $KINDS; do
    d="$HARNESS_DIR/$kind"
    if [ -d "$d" ]; then continue; fi
    if $DRY_RUN; then
        log "[DRY RUN] Would create $(display_path "$d")"
    elif mkdir -p "$d"; then
        log "Created $(display_path "$d")"
    else
        log_error "Cannot create $(display_path "$d")"
        write_summary ERROR "$TOOL" "$(short "cannot create $kind/")"
    fi
done

# =========================================================================
# 4. Plan: every source file, conflicts resolved (first source wins)
# =========================================================================
PLAN="$WORK/plan.tsv"     # kind <TAB> source <TAB> dest <TAB> item
SEEN="$WORK/seen.tsv"     # kind <TAB> lowercased unit <TAB> source label <TAB> unit
LISTED="$WORK/listed.txt" # kind <TAB> source label, per source listed this run (section 5b:
                          # only these retire names, per kind)
: > "$PLAN"
: > "$SEEN"
: > "$LISTED"
DUPLICATES=0

# seen_winner KIND KEY -- "label<TAB>unit" of the source that claimed KEY first; "" when none
seen_winner() {
    perl -e '
        my ($f, $kind, $key) = @ARGV;
        open my $h, "<", $f or die "cannot read $f: $!\n";
        while (my $l = <$h>) {
            chomp $l;
            my @a = split /\t/, $l, 4;
            if ($a[0] eq $kind && $a[1] eq $key) { print "$a[2]\t$a[3]"; exit 0; }
        }
    ' "$SEEN" "$1" "$2"
}

# add_source KIND LABEL SRC_DIR DEST_DIR LAYOUT
#   LAYOUT tree   : every file, relative paths kept, no conflicts (reference, registries)
#          flat   : top-level files only; unit = file name (hooks)
#          flat-md: top-level *.md files only; unit = file name (rules)
#          units  : files inside top-level directories; unit = directory name (skills)
add_source() {
    local kind="$1" label="$2" src_dir="$3" dest_dir="$4" layout="$5"
    if [ ! -d "$src_dir" ]; then
        log "Source $label not found ($(display_path "$src_dir")) -- skipped"
        return 0
    fi
    # 2>/dev/null: rev-parse fails outside a git work tree; that failure is the answer.
    if ! git -C "$src_dir" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        log_error "Source $label ($(display_path "$src_dir")) is not in a git work tree -- skipped (only git-tracked files are deployed)"
        write_summary ERROR "$TOOL" "$(short "$label: not a git checkout")"
        return 0
    fi
    local ls="$WORK/ls.z"
    if ! git -C "$src_dir" ls-files -z > "$ls" 2> "$WORK/ls.err"; then
        log_error "Source $label: git ls-files failed in $(display_path "$src_dir"): $(cat "$WORK/ls.err")"
        write_summary ERROR "$TOOL" "$(short "$label: git ls-files failed")"
        return 0
    fi
    if ! printf '%s\t%s\n' "$kind" "$label" >> "$LISTED"; then
        log_error "Source $label: cannot record it as listed -- its retired $kind are kept this run"
        write_summary ERROR "$TOOL" "$(short "$label: not recorded")"
    fi
    local rel base unit lc winner w_label w_unit last_unit="" keep_unit=true n=0
    while IFS= read -r -d '' rel <&4; do
        base="${rel##*/}"
        case "$base" in
            *.bak.*) log_detail "skip backup copy: $label/$rel"; continue ;;
        esac
        unit=""
        case "$layout" in
            flat|flat-md)
                case "$rel" in
                    */*) log_detail "skip nested file in a flat source: $label/$rel"; continue ;;
                esac
                if [ "$layout" = "flat-md" ]; then
                    case "$rel" in
                        *.md) ;;
                        *) log_detail "skip non-.md file in a rules source: $label/$rel"; continue ;;
                    esac
                fi
                unit="$rel" ;;
            units)
                case "$rel" in
                    */*) unit="${rel%%/*}" ;;
                    *) log_detail "skip file outside a skill directory: $label/$rel"; continue ;;
                esac
                # Not a skill name (the manifest's name rule): hidden or a backup directory
                case "$unit" in
                    .*|*.bak.*) log_detail "skip file in a hidden or backup directory: $label/$rel"; continue ;;
                esac ;;
        esac
        if [ -n "$unit" ] && [ "$unit" != "$last_unit" ]; then
            last_unit="$unit"
            lc=$(printf '%s' "$unit" | tr '[:upper:]' '[:lower:]')
            if ! winner=$(seen_winner "$kind" "$lc"); then
                log_error "Source $label: conflict lookup failed for $unit -- skipped"
                write_summary ERROR "$TOOL" "$(short "$unit: lookup failed")"
                keep_unit=false
                continue
            fi
            if [ -z "$winner" ]; then
                printf '%s\t%s\t%s\t%s\n' "$kind" "$lc" "$label" "$unit" >> "$SEEN"
                keep_unit=true
            else
                w_label="${winner%%$'\t'*}"
                w_unit="${winner#*$'\t'}"
                if [ "$w_label" = "$label" ] && [ "$w_unit" = "$unit" ]; then
                    keep_unit=true
                else
                    keep_unit=false
                    DUPLICATES=$((DUPLICATES + 1))
                    log_error "Duplicate $kind name: $unit in $label ($(display_path "$src_dir/$unit")) skipped; kept $w_unit from $w_label (first source wins)"
                    write_summary ERROR "$TOOL" "$(short "$unit: dup in $label")"
                fi
            fi
        fi
        if [ -n "$unit" ] && ! $keep_unit; then continue; fi
        if [ ! -f "$src_dir/$rel" ]; then
            log_warn "Source $label: $rel is tracked but missing on disk -- skipped"
            continue
        fi
        printf '%s\t%s\t%s\t%s\n' "$kind" "$src_dir/$rel" "$dest_dir/$rel" "$kind/$rel" >> "$PLAN"
        n=$((n + 1))
    done 4< "$ls"
    log_detail "source $label: $n file(s) planned"
}

add_source reference  "reference"        "$REPO_DIR/reference"       "$HARNESS_DIR/reference"  tree
add_source registries "registries"       "$REPO_DIR/registries"      "$HARNESS_DIR/registries" tree
add_source hooks      "shared/hooks"     "$REPO_DIR/shared/hooks"    "$HARNESS_DIR/hooks"      flat
add_source hooks      ".claude/hooks"    "$REPO_DIR/.claude/hooks"   "$HARNESS_DIR/hooks"      flat
add_source skills     "shared/skills"    "$REPO_DIR/shared/skills"   "$HARNESS_DIR/skills"     units
add_source skills     ".claude/skills"   "$REPO_DIR/.claude/skills"  "$HARNESS_DIR/skills"     units
add_source rules      "shared/rules"     "$REPO_DIR/shared/rules"    "$HARNESS_DIR/rules"      flat-md
add_source rules      ".claude/rules"    "$REPO_DIR/.claude/rules"   "$HARNESS_DIR/rules"      flat-md
if [ -n "$DOTPROFILE" ]; then
    add_source rules  "dotprofile"        "$DOTPROFILE/claude/rules"  "$HARNESS_DIR/rules"  flat-md
    add_source skills "dotprofile/skills" "$DOTPROFILE/claude/skills" "$HARNESS_DIR/skills" units
fi
# bin: the harness Python CLIs (the list aitools-install's ~/.aitools/bin step deploys)
for cli in harness-db.py read-session.py read-session-full.py; do
    if [ -f "$SCRIPT_DIR/$cli" ]; then
        printf '%s\t%s\t%s\t%s\n' bin "$SCRIPT_DIR/$cli" "$HARNESS_DIR/bin/$cli" "bin/$cli" >> "$PLAN"
    else
        log_warn "bin: $cli not found at $(display_path "$SCRIPT_DIR/$cli") -- skipped"
    fi
done

# =========================================================================
# 5. Deploy every planned file
# =========================================================================
N_ADDED=0; N_UPDATED=0; N_VERIFIED=0; N_ACCEPTED=0; N_SKIPPED=0; N_FAILED=0
N_WOULD_CREATE=0; N_WOULD_UPDATE=0

# fix_exec SRC DEST -- a deployed copy of an executable source is executable too
fix_exec() {
    if [ -x "$1" ] && [ -f "$2" ] && [ ! -x "$2" ]; then
        if chmod +x "$2"; then
            log "Set executable: $(display_path "$2")"
        else
            log_error "Cannot set the executable bit on $(display_path "$2")"
            write_summary ERROR "$TOOL" "$(short "chmod failed: ${2##*/}")"
        fi
    fi
}

# deploy_one SRC DEST ITEM. Not run in a subshell: [x]abort exits 2 from here.
deploy_one() {
    local src="$1" dest="$2" item="$3" content
    if ! content=$(cat "$src"); then
        log_error "Failed: $item: cannot read $(display_path "$src")"
        N_FAILED=$((N_FAILED + 1))
        write_summary DETAIL "$TOOL" "$(short "failed: $item")"
        return 0
    fi
    if $DRY_RUN; then
        # Count what the library's dry run reports (same newline normalization).
        if [ ! -f "$dest" ]; then
            N_WOULD_CREATE=$((N_WOULD_CREATE + 1))
        elif [ "$(perl -0777 -pe 's/[\r\n]+$/\n/' "$dest")" != "$(printf '%s' "$content" | perl -0777 -pe 's/[\r\n]+$/\n/')" ]; then
            N_WOULD_UPDATE=$((N_WOULD_UPDATE + 1))
        fi
    fi
    deploy_managed_file "$content" "$dest" "$TOOL" "$item" "$src"
    case "$MANAGED_FILE_RESULT" in
        created)
            N_ADDED=$((N_ADDED + 1)); fix_exec "$src" "$dest" ;;
        updated)
            N_UPDATED=$((N_UPDATED + 1)); fix_exec "$src" "$dest" ;;
        verified)
            N_VERIFIED=$((N_VERIFIED + 1))
            if ! $DRY_RUN; then fix_exec "$src" "$dest"; fi ;;
        "accept & adopt")
            # The library wrote the adopt target and WARNs when it is a protected file.
            N_ACCEPTED=$((N_ACCEPTED + 1))
            write_summary DETAIL "$TOOL" "$(short "accept & adopt: $item")" ;;
        skipped)
            N_SKIPPED=$((N_SKIPPED + 1))
            write_summary DETAIL "$TOOL" "$(short "skipped: $item")" ;;
        failed)
            # The library logged the reason with log_error and restored the files.
            N_FAILED=$((N_FAILED + 1))
            write_summary DETAIL "$TOOL" "$(short "failed: $item")" ;;
        *)
            log_error "Failed: $item: unexpected deploy result '$MANAGED_FILE_RESULT'"
            N_FAILED=$((N_FAILED + 1))
            write_summary DETAIL "$TOOL" "$(short "failed: $item")" ;;
    esac
}

N_PLANNED=0
# fd 3 carries the plan so stdin stays the terminal for the review menu.
while IFS=$'\t' read -r kind src dest item <&3; do
    [ -n "$kind" ] || continue
    N_PLANNED=$((N_PLANNED + 1))
    deploy_one "$src" "$dest" "$item"
done 3< "$PLAN"

# =========================================================================
# 5b. Rules manifest and skills manifest, retired rules and skills
# =========================================================================
# ~/.aitools/rules/.aitools-rules-manifest and ~/.aitools/skills/.aitools-skills-manifest.
# The fan-out consumers (setup-user-claude, setup-user-cursor) read them for each
# name's source and for the names to retire. Format v1, one per kind: UTF-8, LF,
# first line "# aitools <kind> manifest v1", then "<name><TAB><source>" sorted by
# name (byte order); name = a rule's file name or a skill's directory name, as
# found on disk; source: shared (aitools shared/<kind>), aitools (aitools
# .claude/<kind>), dotprofile (dotprofile claude/<kind>), retired. The source is
# the one that won (first source wins). The rules manifest has no .md extension
# (consumers that copy *.md never copy it); the skills manifest is a file, not a
# directory (consumers that copy skill directories never copy it).
# Retired: a name in the previous manifest that no source has this run (names
# compared case-insensitively). Only a source of the same kind listed this run
# can retire its names; a name whose source was not listed (not found, not a git
# checkout, ls-files failed, no dotprofile) keeps its line. A retired rule's file
# is backed up and removed; a retired skill's directory is backed up with
# backup_dir, the backup verified, then removed (on every run while it is
# there); the line stays until a source has the name again. No previous
# manifest (first run): nothing is retired. A previous manifest with another
# header: warning, nothing retired, rewritten.
RULES_MANIFEST_HEADER="# aitools rules manifest v1"
SKILLS_MANIFEST_HEADER="# aitools skills manifest v1"
N_RETIRED=0

# harness_manifest_plan KIND HEADER PREV NEW ACTIONS -- from $SEEN (the winners of
# KIND), $LISTED and the previous manifest PREV (may be absent): write the new
# manifest to NEW and one action per line to ACTIONS: "retire<TAB>name<TAB>was"
# (retired this run), "stale<TAB>name" (retired before), "keep<TAB>name<TAB>source"
# (source not listed this run), "warn<TAB>message". KIND: rules | skills. Exit
# non-zero (message on stderr) on any read or write failure.
harness_manifest_plan() {
    perl -e '
        my ($kind, $header, $seen, $listed, $prev, $new, $actions) = @ARGV;
        my %labels = (
            rules  => { "shared/rules"  => "shared", ".claude/rules"  => "aitools", "dotprofile"        => "dotprofile" },
            skills => { "shared/skills" => "shared", ".claude/skills" => "aitools", "dotprofile/skills" => "dotprofile" },
        );
        my %name_ok = (
            rules  => sub { $_[0] =~ /\A[^\/\\]+\.md\z/ && $_[0] !~ /\.bak\./ },
            skills => sub { $_[0] =~ /\A[^\/\\.][^\/\\]*\z/ && $_[0] !~ /\.bak\./ },
        );
        die "unknown manifest kind: $kind\n" unless $labels{$kind};
        my %source_of = %{ $labels{$kind} };
        my %label_of = reverse %source_of;
        my (%lines, %claimed, %listed);
        open my $s, "<:raw", $seen or die "cannot read $seen: $!\n";
        while (my $l = <$s>) {
            chomp $l;
            my ($k, $lc, $label, $unit) = split /\t/, $l, 4;
            next unless $k eq $kind;
            my $src = $source_of{$label};
            die "unknown $kind source label: $label\n" unless defined $src;
            $lines{$unit} = $src;
            $claimed{lc $unit} = 1;
        }
        close $s;
        open my $ls, "<:raw", $listed or die "cannot read $listed: $!\n";
        while (my $l = <$ls>) {
            chomp $l;
            my ($k, $label) = split /\t/, $l, 2;
            $listed{$label} = 1 if $k eq $kind && defined $label;
        }
        close $ls;
        open my $a, ">:raw", $actions or die "cannot write $actions: $!\n";
        if (-e $prev) {
            open my $p, "<:raw", $prev or die "cannot read $prev: $!\n";
            my $head = <$p>;
            $head = "" unless defined $head;
            $head =~ s/\A\xEF\xBB\xBF//;   # a UTF-8 BOM (as the .ps1 reader skips it)
            $head =~ s/\r?\n\z//;
            if ($head ne $header) {
                print $a "warn\tthe first line is not \"$header\" -- nothing retired this run\n";
            } else {
                while (my $l = <$p>) {
                    $l =~ s/\r?\n\z//;
                    next if $l eq "";
                    my ($name, $src) = split /\t/, $l, 2;
                    $src = "" unless defined $src;
                    if (!$name_ok{$kind}->($name) || $src !~ /\A(?:shared|aitools|dotprofile|retired)\z/) {
                        (my $show = $l) =~ s/\t/<TAB>/g;
                        print $a "warn\tline ignored: $show\n";
                        next;
                    }
                    next if $claimed{lc $name};          # a source has it this run
                    if ($src eq "retired") {
                        $lines{$name} = "retired";
                        print $a "stale\t$name\n";
                    } elsif ($listed{$label_of{$src}}) {
                        $lines{$name} = "retired";
                        print $a "retire\t$name\t$src\n";
                    } else {
                        $lines{$name} = $src;
                        print $a "keep\t$name\t$src\n";
                    }
                }
            }
            close $p;
        }
        close $a or die "cannot write $actions: $!\n";
        open my $n, ">:raw", $new or die "cannot write $new: $!\n";
        print $n "$header\n";
        print $n "$_\t$lines{$_}\n" for sort keys %lines;
        close $n or die "cannot write $new: $!\n";
    ' "$1" "$2" "$SEEN" "$LISTED" "$3" "$4" "$5"
}

# retire_rule_file NAME -- back up and remove ~/.aitools/rules/NAME (a retired rule)
retire_rule_file() {
    local name="$1" f="$HARNESS_DIR/rules/$1"
    if $DRY_RUN; then
        log "[DRY RUN] Would back up and remove $(display_path "$f") (retired rule)"
        return 0
    fi
    backup_file "$f"
    if ! $BACKUP_FILE_OK; then
        log_error "Retired rule $name: backup failed -- $(display_path "$f") not removed"
        write_summary ERROR "$TOOL" "$(short "retire failed: $name")"
        return 0
    fi
    if ! rm -f "$f"; then
        log_error "Retired rule $name: cannot remove $(display_path "$f")"
        write_summary ERROR "$TOOL" "$(short "retire failed: $name")"
        return 0
    fi
    N_RETIRED=$((N_RETIRED + 1))
    log "Removed $(display_path "$f") (retired rule; backup kept)"
    write_summary DETAIL "$TOOL" "$(short "retired: rules/$name")"
}

# skill_backups NAME -- the <NAME>.bak.* directories beside ~/.aitools/skills/NAME,
# one per line (names compared literally, not as a glob). Exit non-zero on a
# listing failure.
skill_backups() {
    perl -e '
        my ($dir, $name) = @ARGV;
        opendir my $d, $dir or die "cannot list $dir: $!\n";
        my $p = "$name.bak.";
        print "$_\n" for sort grep { substr($_, 0, length $p) eq $p && -d "$dir/$_" && !-l "$dir/$_" } readdir $d;
        closedir $d;
    ' "$HARNESS_DIR/skills" "$1"
}

# retire_skill_dir NAME -- back up ~/.aitools/skills/NAME with backup_dir, verify a
# new <NAME>.bak.<UTC> directory holds the same files, then remove NAME
# (a retired skill). backup_dir reports no result: the new backup directory is
# the proof (it backs up only a directory with a top-level *.md, e.g. SKILL.md).
retire_skill_dir() {
    local name="$1" d="$HARNESS_DIR/skills/$1" before after bak
    if $DRY_RUN; then
        log "[DRY RUN] Would back up and remove $(display_path "$d") (retired skill)"
        return 0
    fi
    if ! before=$(skill_backups "$name" 2> "$WORK/skill-bak.err"); then
        log_error "Retired skill $name: $(cat "$WORK/skill-bak.err") -- $(display_path "$d") not removed"
        write_summary ERROR "$TOOL" "$(short "retire failed: $name")"
        return 0
    fi
    backup_dir "$d"
    if ! after=$(skill_backups "$name" 2> "$WORK/skill-bak.err"); then
        log_error "Retired skill $name: $(cat "$WORK/skill-bak.err") -- $(display_path "$d") not removed"
        write_summary ERROR "$TOOL" "$(short "retire failed: $name")"
        return 0
    fi
    # The newest backup not listed before the call (names end in a sortable UTC stamp)
    if ! bak=$(perl -e 'my %b = map { $_ => 1 } split /\n/, $ARGV[0]; my @n = grep { !$b{$_} } split /\n/, $ARGV[1]; print $n[-1] if @n' "$before" "$after"); then
        bak=""   # reported as "no new backup" just below
    fi
    if [ -z "$bak" ]; then
        log_error "Retired skill $name: backup failed (no new $name.bak.* directory) -- $(display_path "$d") not removed"
        write_summary ERROR "$TOOL" "$(short "retire failed: $name")"
        return 0
    fi
    # diff exits 1 on a difference, 2 on trouble: either way the backup is not proven.
    if ! diff -r -q "$d" "$HARNESS_DIR/skills/$bak" > "$WORK/skill-bak.diff" 2>&1; then
        log_error "Retired skill $name: backup $(display_path "$HARNESS_DIR/skills/$bak") differs from the directory ($(head -n 1 "$WORK/skill-bak.diff")) -- not removed"
        write_summary ERROR "$TOOL" "$(short "retire failed: $name")"
        return 0
    fi
    if ! rm -rf "$d" || [ -e "$d" ]; then
        log_error "Retired skill $name: cannot remove $(display_path "$d")"
        write_summary ERROR "$TOOL" "$(short "retire failed: $name")"
        return 0
    fi
    N_RETIRED=$((N_RETIRED + 1))
    log "Removed $(display_path "$d") (retired skill; backup $(display_path "$HARNESS_DIR/skills/$bak"))"
    write_summary DETAIL "$TOOL" "$(short "retired: skills/$name")"
}

# write_harness_manifest KIND -- section 5b for one kind (rules | skills): retire,
# then write the manifest (temp file + move)
write_harness_manifest() {
    local kind="$1" header title noun
    case "$kind" in
        rules)  header="$RULES_MANIFEST_HEADER";  title="Rules";  noun="rule" ;;
        skills) header="$SKILLS_MANIFEST_HEADER"; title="Skills"; noun="skill" ;;
    esac
    local manifest="$HARNESS_DIR/$kind/.aitools-$kind-manifest"
    local new="$WORK/$kind-manifest.new" actions="$WORK/$kind-manifest.actions"
    local tmp="$manifest.tmp" act name extra n p
    if ! harness_manifest_plan "$kind" "$header" "$manifest" "$new" "$actions" 2> "$WORK/$kind-manifest.err"; then
        log_error "$title manifest: $(cat "$WORK/$kind-manifest.err") -- manifest not written, nothing retired"
        write_summary ERROR "$TOOL" "$kind manifest not written"
        return 0
    fi
    while IFS=$'\t' read -r act name extra <&5; do
        case "$act" in
            warn)
                log_warn "$title manifest $(display_path "$manifest"): $name" ;;
            keep)
                log "$title manifest: $name kept as $extra (source not listed this run -- not retired)" ;;
            retire|stale)
                if [ "$act" = "retire" ]; then
                    log "Retired $noun: $name (was $extra; no source has it now)"
                fi
                p="$HARNESS_DIR/$kind/$name"
                if [ "$kind" = "rules" ]; then
                    if [ -f "$p" ] || [ -L "$p" ]; then retire_rule_file "$name"; fi
                elif [ -d "$p" ] && [ ! -L "$p" ]; then
                    retire_skill_dir "$name"
                elif [ -e "$p" ] || [ -L "$p" ]; then
                    log_warn "Retired skill $name: $(display_path "$p") is not a directory -- left alone"
                fi ;;
        esac
    done 5< "$actions"
    n=$(perl -ne '$n++ if $. > 1; END { print $n + 0 }' "$new")
    if $DRY_RUN; then
        log "[DRY RUN] Would write $(display_path "$manifest") ($n $noun line(s))"
        return 0
    fi
    if ! cp "$new" "$tmp"; then
        log_error "$title manifest: cannot write $(display_path "$tmp") -- manifest not written"
        write_summary ERROR "$TOOL" "$kind manifest not written"
        return 0
    fi
    if ! mv -f "$tmp" "$manifest"; then
        log_error "$title manifest: cannot move $(display_path "$tmp") to $(display_path "$manifest") -- manifest not written"
        write_summary ERROR "$TOOL" "$kind manifest not written"
        if ! rm -f "$tmp"; then log_warn "Cannot remove $(display_path "$tmp")"; fi
        return 0
    fi
    log "$title manifest: wrote $(display_path "$manifest") ($n $noun line(s))"
}

