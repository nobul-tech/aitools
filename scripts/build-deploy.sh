BLOCK
    bash_logging_helpers "setup-user-cursor"
    bash_os_guard
    cat <<'BLOCK'

CURSOR_DIR="$HOME/.cursor"
CLI_CONFIG="$CURSOR_DIR/cli-config.json"

# --- 1. ripgrep (rg) ---
log "Step 1: ripgrep (rg)"

if command -v rg &>/dev/null; then
    RG_VERSION=$(rg --version | head -1)
    log_ok "Already installed: $RG_VERSION"
else
    if command -v brew &>/dev/null; then
        log "Installing ripgrep via brew..."
        brew install ripgrep
        if command -v rg &>/dev/null; then
            log_ok "Installed: $(rg --version | head -1)"
        else
            log_error "brew install completed but 'rg' not found in PATH"
        fi
    else
        log_error "Homebrew not found. Install ripgrep manually: brew install ripgrep"
    fi
fi

# --- 2. Cursor CLI (agent) ---
log "Step 2: Cursor CLI (agent)"

if command -v agent &>/dev/null; then
    AGENT_VERSION=$(agent --version)
    log_ok "Already installed: $AGENT_VERSION"
else
    log "Installing Cursor CLI..."
    curl https://cursor.com/install -fsS | bash
    if command -v agent &>/dev/null; then
        log_ok "Installed: $(agent --version)"
    else
        log_error "Cursor CLI install completed but 'agent' not found in PATH (restart terminal)"
    fi
fi

# --- 3. cli-config.json ---
log "Step 3: cli-config.json"

EXPECTED_CONFIG='{
  "version": 1,
  "editor": {
    "vimMode": false
  },
  "permissions": {
    "allow": [],
    "deny": []
  }
}'

mkdir -p "$CURSOR_DIR"

if [ -f "$CLI_CONFIG" ]; then
    EXISTING_CONFIG=$(cat "$CLI_CONFIG")
    if [ "$EXISTING_CONFIG" = "$EXPECTED_CONFIG" ]; then
        log_ok "Already up to date: $CLI_CONFIG"
    else
        printf '%s' "$EXPECTED_CONFIG" > "$CLI_CONFIG"
        log_ok "Updated: $CLI_CONFIG"
    fi
else
    printf '%s' "$EXPECTED_CONFIG" > "$CLI_CONFIG"
    log_ok "Created: $CLI_CONFIG"
fi

# --- 4. User Rules ---
log "Step 4: User Rules (embedded)"

# --- Embedded User Rules (from shared/cursor-rules/user-rules.md) ---
BLOCK
    echo 'read -r -d "" USER_RULES_CONTENT <<'"'"'__EMBEDDED_USER_RULES__'"'"' || true'
    echo "$USER_RULES_CONTENT"
    echo '__EMBEDDED_USER_RULES__'
    cat <<'BLOCK'

if [ -t 1 ]; then
    # Interactive: copy to clipboard
    if command -v pbcopy &>/dev/null; then
        printf '%s' "$USER_RULES_CONTENT" | pbcopy
        log_ok "Copied User Rules to clipboard"
    elif command -v xclip &>/dev/null; then
        printf '%s' "$USER_RULES_CONTENT" | xclip -selection clipboard
        log_ok "Copied User Rules to clipboard (xclip)"
    else
        log_warn "No clipboard command found (pbcopy/xclip). Copy manually from log."
    fi
    log "Paste User Rules into: Cursor Settings > Rules"
else
    # Non-interactive: skip clipboard
    log_ok "User Rules embedded and ready"
fi
BLOCK
    bash_exit_footer
} > "$DEPLOY_DIR/setup-user-cursor.sh"

