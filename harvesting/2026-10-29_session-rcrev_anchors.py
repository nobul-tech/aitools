def show(ref: str, path: str) -> str | None:
    p = subprocess.run(["git", "-C", R, "show", f"{ref}:{path}"], capture_output=True)
    if p.returncode != 0:
        return None
    return p.stdout.decode("utf-8", "replace")


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.replace("\r", ""))


refs = sys.argv[1:] or list(REFS)
for bid, path, old in A:
    row = []
    for k in refs:
        t = show(REFS[k], path)
        if t is None:
            row.append(f"{k}:nofile")
            continue
        ex = t.replace("\r\n", "\n").count(old)
        nm = norm(t).count(norm(old))
        row.append(f"{k}:{ex}" + ("" if ex == nm else f"/{nm}n"))
    print(f"{bid:8} {path:48} " + " ".join(row))
